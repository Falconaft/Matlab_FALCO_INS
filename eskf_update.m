function kf = eskf_update(kf, z, H, R)
%ESKF_UPDATE  Шаг коррекции ESKF (measurement update) по невязке z.
%
%   Классический шаг коррекции фильтра Калмана с Joseph-формой обновления
%   ковариации (численно устойчивая, гарантирует симметрию и положительную
%   определённость P). Работает с error-state: корректирует kf.x (ошибку),
%   которая затем применяется к номинальному состоянию в eskf_feedback.
%
%   Уравнения:
%     K = P·H'·(H·P·H' + R)^{-1}              усиление Калмана
%     x = x + K·(z - H·x)                     коррекция ошибки
%     P = (I-K·H)·P·(I-K·H)' + K·R·K'         Joseph form
%
%   Вход:
%     kf - структура фильтра (kf.x - error-state 21x1, kf.P - ковариация 21x21)
%     z  - невязка измерения (m x 1): [r_nav-r_gnss; v_nav-v_gnss]
%     H  - матрица измерений (m x 21)
%     R  - ковариация шума измерений (m x m)
%   Выход:
%     kf - обновлённая структура (kf.x, kf.P скорректированы)
%          дополнительно kf.S - инновационная ковариация H·P·H' + R,
%          нужна для расчёта NIS (проверка состоятельности фильтра)

    RANK = size(kf.P, 1);
    I = eye(RANK);

    % =====================================================================
    % Шаг 5.9.1: Инновационная ковариация и усиление Калмана
    % =====================================================================
    S = H * kf.P * H' + R;              % ковариация невязки (innovation cov)
    K = kf.P * H' / S;                  % усиление Калмана (right division = ·inv(S))

    % Сохраняем инновационную ковариацию для расчёта NIS в вызывающем коде.
    % NIS = z' * S^-1 * z — единственная метрика состоятельности, вычислимая
    % БЕЗ знания истины, поэтому пригодна и для бортовой диагностики.
    kf.S = S;

    % =====================================================================
    % Шаг 5.9.2: Коррекция error-state
    % =====================================================================
    % Невязка уже есть z; предсказанное измерение ошибки = H·kf.x
    % (kf.x обычно 0 после reset, но в общем случае учитываем)
    innovation = z - H * kf.x;
    kf.x = kf.x + K * innovation;

    % =====================================================================
    % Шаг 5.9.3: Обновление ковариации (Joseph form)
    % =====================================================================
    % Joseph form: численно устойчивее, чем (I-KH)P - сохраняет симметрию
    % и положительную определённость даже при ошибках округления.
    IKH = I - K * H;
    kf.P = IKH * kf.P * IKH' + K * R * K';

    % Симметризация (страховка от накопления численной несимметрии)
    kf.P = (kf.P + kf.P') / 2;
end
