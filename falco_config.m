function cfg = falco_config()
%FALCO_CONFIG  БАЗОВАЯ конфигурация прогона навигационного контура.
%
%   Возвращает только те параметры, которые ДЕЙСТВИТЕЛЬНО общие для всех
%   сценариев. Значения, специфичные для конкретного драйвера, каждый драйвер
%   переопределяет ЯВНО после вызова этой функции.
%
%   НАМЕРЕННО НЕ УНИФИЦИРУЮТСЯ (остаются в драйверах):
%     sigma_pos / sigma_vel — у main_step10_budget они 1.5 и 0.05 против 5 и 0.1
%                             у остальных; унификация сместила бы результаты
%                             бюджета ошибок;
%     P0_pos                — 3.0 в бюджете против 5.0 в остальных;
%     f_diag                — 10 Гц в main_step8, 1 Гц в МК-драйверах,
%                             250 Гц в тесте численного пола;
%     align_err / align_sigma — детерминированный вектор в одиночных прогонах
%                             против СКО для розыгрыша в Монте-Карло;
%     seed / base_seed      — задаётся сценарием;
%     outage                — вычисляется из параметров траектории.
%
%   ТИПОВОЕ ПРИМЕНЕНИЕ В ДРАЙВЕРЕ:
%       cfg = falco_config();
%       cfg.sigma_pos = 1.5*ones(3,1);          % переопределение
%       cfg.f_diag    = 1;
%       cfg.diag_decim = round(cfg.fnav / cfg.f_diag);   % ОБЯЗАТЕЛЬНО после
%                                                        % смены f_diag или fnav
%
%   Выход: cfg - структура базовой конфигурации

    % =====================================================================
    % ЧАСТОТЫ
    % =====================================================================
    % Частота навигатора ДОЛЖНА быть целым делителем частоты истины
    % (см. traj_params.p.dt = 0.0005, то есть 2000 Гц; 2000/400 = 5).
    % Нарушение прерывается assert-ом в make_increments.
    cfg.fnav   = 400;              % частота навигатора [Гц]
    cfg.f_gnss = 10;               % частота обновлений GNSS [Гц]

    % Частота записи диагностики. Значение по умолчанию; драйверы, которым
    % нужна другая, переопределяют её И ПЕРЕСЧИТЫВАЮТ diag_decim.
    cfg.f_diag     = 10;                                  % [Гц]
    cfg.diag_decim = round(cfg.fnav / cfg.f_diag);

    % =====================================================================
    % МОДЕЛЬ ФИЛЬТРА
    % =====================================================================
    cfg.corrtime = 1000;           % время корреляции Гаусса-Маркова [с]

    % =====================================================================
    % ГЕОМЕТРИЯ УСТАНОВКИ
    % =====================================================================
    cfg.lever = [0.1; 0.0; -0.1];  % плечо антенны GNSS от IMU в body [м]

    % =====================================================================
    % ШУМ ИЗМЕРЕНИЙ GNSS (базовые значения; бюджет ошибок их переопределяет)
    % =====================================================================
    cfg.sigma_pos = 5.0*ones(3,1);   % СКО шума позиции GNSS [м]
    cfg.sigma_vel = 0.1*ones(3,1);   % СКО шума скорости GNSS [м/с]

    % =====================================================================
    % НАЧАЛЬНАЯ КОВАРИАЦИЯ (позиция/скорость; ориентация — в драйвере,
    % так как связана со сценарием выставки)
    % =====================================================================
    cfg.P0_pos = [5.0; 5.0; 5.0];    % [м]
    cfg.P0_vel = [0.1; 0.1; 0.1];    % [м/с]

    % =====================================================================
    % ВРЕМЕННОЙ СДВИГ GNSS ОТНОСИТЕЛЬНО ИНС (B4)
    % =====================================================================
    % ЧТО ИМЕННО МОДЕЛИРУЕТСЯ: НЕКОМПЕНСИРОВАННОЕ РАССОГЛАСОВАНИЕ ЭПОХ.
    % Измерение относится к моменту
    %     t_meas = t_nav - gnss_time_offset
    % но фильтр обрабатывает его КАК ТЕКУЩЕЕ: предсказание, H и коррекция
    % остаются привязанными к t_nav. То есть моделируется не транспортная
    % задержка сама по себе, а отсутствие её компенсации в навигаторе.
    %
    % ЧЕГО МОДЕЛЬ ПОКА НЕ ОХВАТЫВАЕТ: раздельные t_meas (момент, к которому
    % относится решение приёмника) и t_arrival (момент поступления данных в
    % навигатор). Сейчас они слиты в один параметр. Разделение понадобится,
    % когда будет моделироваться буферизация и переменная задержка тракта.
    %
    % Знак только неотрицательный: измерение может быть УСТАРЕВШИМ, но не
    % может относиться к будущему.
    %
    % По умолчанию ВЫКЛЮЧЕНО, поэтому все прежние результаты воспроизводятся
    % без изменений.
    cfg.gnss_time_offset_enable = false;
    cfg.gnss_time_offset        = 0.0;    % [с]

    % Дополнительный model process noise.
    % 0 = исходный физический Q IMU.
    % 1 = добавить ещё 1x мощности ARW/VRW -> итоговые блоки 2x.
    % 3 = добавить ещё 3x -> итоговые блоки 4x.
    cfg.q_model_factor = 0.0;


    % Параметр запуска параллельных вычислений. true/false 
    cfg.use_parallel     = true;
    
end