function [lat, lon, h] = ecef2lla(r, c)
%ECEF2LLA  Преобразование ECEF -> геодезические координаты (WGS-84).
%
%   Итерационный алгоритм Боуринга. Для наших высот (< 30 км) сходится
%   за 4-5 итераций до машинной точности.
%
%   Вход:  r - позиция ECEF (3x1) [м]
%          c - константы (c.A_E большая полуось, c.E2 квадрат эксцентриситета)
%   Выход: lat - широта [рад], lon - долгота [рад], h - высота [м]

    X = r(1);   Y = r(2);   Z = r(3);

    lon = atan2(Y, X);
    p   = hypot(X, Y);

    % Начальное приближение (сферическое)
    lat = atan2(Z, p*(1 - c.E2));

    % Итерации Боуринга
    for i = 1:6
        N   = c.A_E / sqrt(1 - c.E2*sin(lat)^2);
        h   = p/cos(lat) - N;
        lat = atan2(Z, p*(1 - c.E2*N/(N + h)));
    end

    N = c.A_E / sqrt(1 - c.E2*sin(lat)^2);
    h = p/cos(lat) - N;
end
