function M = imu_error_matrix(scale, misalign, ortho)
%IMU_ERROR_MATRIX  Матрица ошибок триады датчиков (Groves eq. 4.16-4.17).
%
%   Измерение искажается как:  v_изм = (I + M)*v_ист + смещение + шум
%
%   ВЫВОД ИЗ ГЕОМЕТРИИ (проверено численно от первых принципов):
%     Датчик i измеряет ПРОЕКЦИЮ вектора на свою чувствительную ось a_i:
%         v_изм,i = (1 + s_i) * (a_i . v_ист)
%     В матричной форме:  v_изм = diag(1+s) * A' * v_ист,  где A = [a1 a2 a3].
%     Отсюда  I + M = diag(1+s)*A',  и при малых отклонениях осей от номинала
%         M ~ diag(s) + D,   D_ij = (da_i)_j,   D_ii ~ 0.
%
%     D — ПРОИЗВОЛЬНАЯ матрица с нулевой диагональю: 6 независимых параметров.
%     Её разложение на антисимметричную и симметричную части исчерпывает их:
%         D = D_анти (3 параметра)  +  D_сим (3 параметра).
%
%   ФИЗИЧЕСКИЙ СМЫСЛ ЧАСТЕЙ:
%
%     diag(scale)      масштабный коэффициент. ЕСТЬ в векторе состояния
%                      фильтра -> оценивается.
%
%     -[misalign x]    АНТИсимметричная часть: вся триада повёрнута как
%                      жёсткое тело относительно корпуса.
%                      Проверено: для поворота на dtheta геометрия даёт
%                      ровно D = -skew(dtheta) (совпадение до машинного нуля).
%                      datasheet: "Misalignment".
%
%     Shear(ortho)/2   СИММЕТРИЧНАЯ внедиагональная часть: оси внутри триады
%                      не строго перпендикулярны.
%                      ВАЖЕН МНОЖИТЕЛЬ 1/2: если угол между осями i и j
%                      отклоняется от 90 град на gamma, то скалярное
%                      произведение осей a_i.a_j = D_ij + D_ji = gamma,
%                      то есть КАЖДЫЙ из двух симметричных элементов равен
%                      gamma/2. Без множителя неортогональность завышается вдвое.
%                      datasheet: "Orthogonality".
%
%   ЗАМЕЧАНИЕ О НАБЛЮДАЕМОСТИ (важно для интерпретации результатов):
%     Жёсткий поворот ГИРОСКОПИЧЕСКОЙ триады эквивалентен постоянному
%     смещению ориентации, поэтому частично поглощается оценкой начальной
%     выставки и наблюдаем фильтром. Жёсткий поворот АКСЕЛЕРОМЕТРИЧЕСКОЙ
%     триады относительно гироскопической — реальная неучтённая ошибка:
%     в состоянии фильтра нет ни поворота триад, ни неортогональности.
%
%   Вход:
%     scale    (3x1) относительные ошибки масштаба по осям [-]
%     misalign (3x1) вектор малого поворота триады [рад]
%     ortho    (3x1) углы НЕОРТОГОНАЛЬНОСТИ [рад] — отклонения от 90 град:
%                    ortho(1) — между осями X и Y
%                    ortho(2) — между осями X и Z
%                    ortho(3) — между осями Y и Z
%   Выход:
%     M (3x3) безразмерная матрица ошибок

    % --- Масштабные коэффициенты: диагональ ---
    M_scale = diag(scale(:));

    % --- Поворот триады как жёсткого тела: антисимметричная часть ---
    M_rot = -skew(misalign(:));

    % --- Неортогональность: симметричная внедиагональная часть ---
    % Множитель 1/2: угол gamma между осями распределяется поровну между
    % двумя симметричными элементами (см. вывод в шапке).
    g_xy = 0.5 * ortho(1);
    g_xz = 0.5 * ortho(2);
    g_yz = 0.5 * ortho(3);
    M_ortho = [   0,   g_xy, g_xz ;
               g_xy,      0, g_yz ;
               g_xz,   g_yz,    0 ];

    M = M_scale + M_rot + M_ortho;
end