function dg_ecef = draw_gravity_anomaly(cfg, Cen, rng_stream)
%DRAW_GRAVITY_ANOMALY  Розыгрыш ошибки гравитационной модели навигатора.
%
%   Реальное поле силы тяжести отличается от модели (нормальное поле + J2)
%   на АНОМАЛИЮ. Навигатор её не знает, поэтому она входит как неучтённое
%   ускорение на всём полёте.
%
%   ДВЕ СОСТАВЛЯЮЩИЕ (в локальной системе ENU):
%
%     Уклонение отвеса (горизонтальные компоненты)
%       Направление реальной вертикали отличается от нормали к эллипсоиду
%       на угол theta. Даёт горизонтальное ускорение g*theta.
%       Типичные значения: 5 угл.сек (равнина) .. 30 угл.сек (горы).
%       ЭТО ГЛАВНОЕ ДЛЯ КВО — горизонтальная ошибка.
%
%     Аномалия силы тяжести (вертикальная компонента)
%       Отклонение модуля g от нормального значения, обычно 20..100 мГал.
%       Влияет в основном на ВЫСОТУ, слабее на КВО.
%
%   ДОПУЩЕНИЕ (явно): аномалия считается ПОСТОЯННОЙ вдоль траектории.
%   Обоснование: характерный масштаб корреляции аномалий поля 10..100 км,
%   дальность полёта ~80 км — то есть трасса укладывается в одну
%   корреляционную ячейку. Для более строгой модели потребовалась бы
%   пространственная модель поля (например EGM2008), что избыточно.
%
%   ВАЖНО: разыгрывается на КАЖДУЮ реализацию Монте-Карло, иначе аномалия
%   стала бы детерминированной и дала бы ложную систематику по ансамблю.
%
%   Вход:
%     cfg        - конфигурация; используются поля (если заданы):
%                  .defl_vert_sigma  СКО уклонения отвеса [рад]
%                  .grav_anom_sigma  СКО аномалии по вертикали [м/с²]
%     Cen        - матрица ECEF->ENU (столбцы: E, N, U) в точке старта
%     rng_stream - поток случайных чисел
%   Выход:
%     dg_ecef (3x1) вектор ошибки гравитационной модели в ECEF [м/с²]

    g0 = 9.80665;

    % --- Параметры со значениями по умолчанию (0 = эффект выключен) ---
    if isfield(cfg, 'defl_vert_sigma')
        defl_sigma = cfg.defl_vert_sigma;
    else
        defl_sigma = 0;
    end
    if isfield(cfg, 'grav_anom_sigma')
        anom_sigma = cfg.grav_anom_sigma;
    else
        anom_sigma = 0;
    end

    % --- Уклонение отвеса: два независимых угла (в плоскостях E и N) ---
    % Горизонтальное ускорение = g * угол отклонения вертикали
    defl_E = defl_sigma * randn(rng_stream);
    defl_N = defl_sigma * randn(rng_stream);
    dg_E = g0 * defl_E;
    dg_N = g0 * defl_N;

    % --- Аномалия по вертикали ---
    dg_U = anom_sigma * randn(rng_stream);

    % --- Перевод из локальной ENU в ECEF ---
    dg_enu  = [dg_E; dg_N; dg_U];
    dg_ecef = Cen * dg_enu;
end
