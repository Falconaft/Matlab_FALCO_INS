function [dg_ecef, info] = draw_gravity_anomaly(cfg, Cen, rng_stream)
%DRAW_GRAVITY_ANOMALY  Розыгрыш аномалии гравитационного поля.
%
%   Реальное поле силы тяжести отличается от модели навигатора (нормальное
%   поле + J2) на АНОМАЛИЮ. Навигатор её не знает, поэтому она входит как
%   неучтённое ускорение на всём полёте.
%
%   ОПРЕДЕЛЕНИЕ ЗНАКА (важно, см. также ins_mech_step):
%       dg = g_true - g_model
%   то есть возвращаемый вектор — аномалия ИСТИННОГО поля относительно
%   модели. Истинная траектория при этом НЕ пересчитывается: эквивалентный
%   эффект вносится вычитанием dg в механизации навигатора, что даёт
%   ошибку ускорения ровно -dg.
%
%   ДВЕ СОСТАВЛЯЮЩИЕ (в локальной системе ENU):
%
%     Уклонение отвеса (горизонтальные компоненты)
%       Направление реальной вертикали отличается от нормали к эллипсоиду
%       на угол theta, что даёт горизонтальное ускорение g0*theta.
%       Типично: 5 угл.сек равнина, 10-20 холмистая местность, 30 горы.
%       ЭТО ГЛАВНОЕ ДЛЯ КВО — именно горизонтальная составляющая.
%
%     Аномалия силы тяжести (вертикальная компонента)
%       Отклонение модуля g от нормального значения, обычно 20..100 мГал
%       (1 мГал = 1e-5 м/с²). Влияет в основном на высоту.
%
%   ДОПУЩЕНИЕ (обозначено явно): аномалия считается ПОСТОЯННОЙ вдоль
%   траектории. Обоснование: характерный масштаб корреляции аномалий поля
%   10..100 км, дальность полёта ~87 км, то есть трасса укладывается в одну
%   корреляционную ячейку. Строгая модель потребовала бы пространственного
%   разложения поля (например EGM2008), что для задачи избыточно.
%
%   ПОТОК СЛУЧАЙНЫХ ЧИСЕЛ: функции передаётся ОТДЕЛЬНЫЙ поток, не тот, из
%   которого разыгрываются ошибки IMU и выставка. Это делает реализацию
%   аномалии независимой от числа обращений к randn в модели датчика:
%   изменение модели IMU не сдвигает разыгранное поле, и B2 можно
%   независимо включать и выключать в бюджете ошибок.
%
%   Вход:
%     cfg        - конфигурация; используются поля (0, если не заданы):
%                  .defl_vert_sigma  СКО уклонения отвеса [рад]
%                  .grav_anom_sigma  СКО аномалии по вертикали [м/с²]
%     Cen        - матрица ENU -> ECEF в точке старта (столбцы E, N, U)
%     rng_stream - ОТДЕЛЬНЫЙ поток случайных чисел для аномалии
%   Выход:
%     dg_ecef (3x1) вектор аномалии поля в ECEF [м/с²]
%     info          структура фактически разыгранных величин (диагностика)

    g0      = 9.80665;
    RAD2SEC = 206265;              % радиан -> угловые секунды
    MPS2MGAL = 1e5;                % м/с² -> мГал

    % --- Параметры со значениями по умолчанию (0 = эффект выключен) ---
    if isfield(cfg, 'defl_vert_sigma')
        defl_sigma = cfg.defl_vert_sigma;
    else
        defl_sigma = 0;
    end
    if isfield(cfg, 'grav_anom_sigma')
        anom_sigma = cfg.grav_anom_sigma;
    else
        anom_sigma = 0;
    end

    % --- Уклонение отвеса: два независимых угла (в плоскостях E и N) ---
    % Горизонтальное ускорение = g0 * угол отклонения вертикали
    defl_E = defl_sigma * randn(rng_stream);
    defl_N = defl_sigma * randn(rng_stream);
    dg_E = g0 * defl_E;
    dg_N = g0 * defl_N;

    % --- Аномалия по вертикали (модуль g) ---
    dg_U = anom_sigma * randn(rng_stream);

    % --- Перевод из локальной ENU в ECEF ---
    dg_enu  = [dg_E; dg_N; dg_U];
    dg_ecef = Cen * dg_enu;

    % =====================================================================
    % ДИАГНОСТИКА: фактически разыгранные величины
    % =====================================================================
    info.defl_E_arcsec     = defl_E * RAD2SEC;
    info.defl_N_arcsec     = defl_N * RAD2SEC;
    info.defl_total_arcsec = hypot(defl_E, defl_N) * RAD2SEC;
    info.anom_vert_mgal    = dg_U * MPS2MGAL;
    info.dg_horiz_mps2     = hypot(dg_E, dg_N);
    info.dg_norm_mps2      = norm(dg_ecef);
end
