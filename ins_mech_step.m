function [nav, aux] = ins_mech_step(nav, dtheta, dvel, dt, c)
%INS_MECH_STEP  Один такт механизации БИНС в ECEF (для работы внутри ESKF).
%
%   Пошаговая форма механизации: чередуется с predict/update фильтра.
%
%   Порядок операций:
%     (а) коррекция измерений: bias/scale (error-of-estimate) + компенсация
%         g-чувствительности гироскопа паспортным коэффициентом
%     (б) поправка на вращение корпуса + скаллинг (two-sample, Savage)
%     (в) проекция удельной силы в ECEF ориентацией НАЧАЛА такта
%     (г) RK4 по связке (r,v) с четырьмя членами механизации
%     (д) обновление кватерниона с коррекцией конинга и поворотом Земли
%
%   ВАЖНО (исправлено после численной проверки):
%     Член 0.5*[dtheta x dvel] — это ПОВОРОТНАЯ ПОПРАВКА (rotation compensation),
%     а НЕ скаллинг. Она приводит приращение скорости к осям тела на НАЧАЛО такта.
%     Поэтому проецировать нужно матрицей ориентации НАЧАЛА такта.
%     Комбинация "поворотная поправка + проекция серединой такта" учитывает
%     поворот ДВАЖДЫ. Проверено численно на траектории с разгоном 17g и
%     вращением 55 °/с: правильные комбинации дают ошибку скорости 9e-5 м/с,
%     неправильные — 0.067 м/с (в 700 раз хуже).
%
%     Собственно СКАЛЛИНГ — только члены 1/12 с приращениями предыдущего такта.
%
%   Вход:
%     nav    - состояние навигатора (.r .v .q .C .bg .ba .sg .sa .dth_prev .dv_prev)
%     dtheta - СЫРОЕ приращение угла с гироскопа за такт (3x1) [рад]
%     dvel   - СЫРОЕ приращение скорости с акселерометра за такт (3x1) [м/с]
%     dt     - длительность такта [с]
%     c      - константы (c.WIE, c.MU, ...)
%   Выход:
%     nav    - обновлённое состояние
%     aux    - .f_b (3x1) [м/с²], .w_b (3x1) [рад/с] — для построения F

    WIEx = skew(c.WIE);

    % =====================================================================
    % Шаг (а): КОРРЕКЦИЯ ИЗМЕРЕНИЙ оценками ошибок IMU
    % =====================================================================
    % Конвенция error-of-estimate: оценки bias/scale ВЫЧИТАЮТСЯ из измерений.
    % bias задан как скорость дрейфа [рад/с],[м/с²] -> за такт умножаем на dt.
    % Сначала акселерометр: скорректированное приращение скорости нужно
    % для компенсации g-чувствительности гироскопа.
    dvl = (eye(3) - diag(nav.sa)) * (dvel - nav.ba*dt);

    % КОМПЕНСАЦИЯ g-SENSITIVITY ГИРОСКОПА.
    % Гироскоп MEMS чувствует удельную силу: w_par = Gg*f. Вклад в приращение
    % угла за такт равен интегралу: integral(Gg*f dt) = Gg*integral(f dt) = Gg*dvel.
    % Поэтому компенсация в форме приращений — просто Gg*dvl, без деления на dt.
    %
    % Используется ПАСПОРТНОЕ значение Gg (калибровка на центрифуге при приёмке).
    % Остаётся нескомпенсированной только ошибка калибровки (см. imu_draw_errors).
    % Без этой компенсации на траектории с ненулевой удельной силой на коасте
    % накапливается ~2 мрад ошибки ориентации за 60 с и ~8 м бокового сноса.
    if isfield(nav, 'Gg_cal') && any(nav.Gg_cal(:) ~= 0)
        dtheta_comp = dtheta - nav.Gg_cal * dvl;
    else
        dtheta_comp = dtheta;
    end

    dth = (eye(3) - diag(nav.sg)) * (dtheta_comp - nav.bg*dt);

    % =====================================================================
    % Шаг (б): ПОВОРОТНАЯ ПОПРАВКА + СКАЛЛИНГ (two-sample, Savage)
    % =====================================================================
    % dv_rot  — поворотная поправка: приводит приращение к осям тела на НАЧАЛО
    %           такта (корпус успевает повернуться, пока копится dvel).
    % dv_scul — собственно скаллинг: согласованные колебания вращения и силы
    %           между соседними тактами.
    dv_rot  = 0.5 * cross(dth, dvl);
    dv_scul = (1/12) * ( cross(nav.dth_prev, dvl) + cross(nav.dv_prev, dth) );
    dv_body = dvl + dv_rot + dv_scul;

    % =====================================================================
    % Шаг (в): ПРОЕКЦИЯ УДЕЛЬНОЙ СИЛЫ ориентацией НАЧАЛА такта
    % =====================================================================
    % dv_body уже приведено к осям тела на начало такта поворотной поправкой,
    % поэтому проецируем матрицей ориентации НАЧАЛА такта (не середины!).
    C_start = nav.C;
    a_sf    = C_start * dv_body / dt;      % среднее кажущееся ускорение в ECEF

    % =====================================================================
    % Шаг (г): RK4 для связки (r, v) — четыре члена механизации
    % =====================================================================
    r_old = nav.r;
    v_old = nav.v;

    % Ошибка гравитационной модели навигатора (аномалия поля, которой
    % навигатор не знает). Физика: акселерометр измеряет удельную силу
    % f = a - g, и она НЕ зависит от того, верна ли наша модель гравитации.
    % Истина:    a_ист = C*f + g_ист
    % Навигатор: a_нав = C*f + g_модель
    % Ошибка ускорения навигатора = g_модель - g_ист = -dg.
    % Поэтому достаточно вычесть dg в механизации — пересчитывать
    % траекторию не нужно, а dg можно разыгрывать на каждой реализации МК.
    if isfield(nav, 'dg_model')
        dg = nav.dg_model;
    else
        dg = zeros(3,1);
    end

    [k1r, k1v] = rv_deriv(r_old,              v_old,              a_sf, WIEx, c, dg);
    [k2r, k2v] = rv_deriv(r_old + 0.5*dt*k1r, v_old + 0.5*dt*k1v, a_sf, WIEx, c, dg);
    [k3r, k3v] = rv_deriv(r_old + 0.5*dt*k2r, v_old + 0.5*dt*k2v, a_sf, WIEx, c, dg);
    [k4r, k4v] = rv_deriv(r_old + dt*k3r,     v_old + dt*k3v,     a_sf, WIEx, c, dg);

    nav.r = r_old + dt/6*(k1r + 2*k2r + 2*k3r + k4r);
    nav.v = v_old + dt/6*(k1v + 2*k2v + 2*k3v + k4v);

    % =====================================================================
    % Шаг (д): ОБНОВЛЕНИЕ ОРИЕНТАЦИИ (конинг + поворот Земли)
    % =====================================================================
    zeta       = -c.WIE * dt;                    % поворот e-системы за такт
    phi_coning = (1/12) * cross(nav.dth_prev, dth);
    phi        = dth + phi_coning;
    q_e        = rotvec2q(zeta);                 % поворот e-системы (слева)
    q_b        = rotvec2q(phi);                  % поворот тела (справа)
    nav.q      = qmul(qmul(q_e, nav.q), q_b);
    nav.q      = nav.q / norm(nav.q);
    nav.C      = q2C(nav.q);

    % =====================================================================
    % Сохранение приращений для two-sample на следующем такте
    % =====================================================================
    nav.dth_prev = dth;
    nav.dv_prev  = dvl;

    % Вспомогательные величины для F-матрицы (средние за такт)
    aux.f_b = dvl / dt;
    aux.w_b = dth / dt;
end


function [dr, dv] = rv_deriv(r, v, a_sf, WIEx, c, dg)
%RV_DERIV  Правая часть ОДУ движения в ECEF (четыре члена механизации).
%   dv/dt = a_sf + g(r) - dg - 2*[w_ie x]*v - [w_ie x]^2 * r
%   dg — ошибка гравитационной модели навигатора (аномалия поля).
    dr = v;
    dv = a_sf + grav_ecef(r, c) - dg - 2*WIEx*v - WIEx*(WIEx*r);
end