%% MAIN_STEP3  Falco NAV - Шаг 3: прямая механизация БИНС и её валидация
%
%  Требует falco_step12.mat (сначала запустить main_step12).
%  Два теста:
%    (1) Дрейф на ПОЛНОЙ траектории (диагностика) при 100/200/400 Гц.
%        Показывает численный "пол" точности и его масштабирование с частотой.
%    (2) Дрейф за 60 с КОАСТА от поджатого GNSS состояния (релевантная метрика).
%        Именно это число определяет вклад численной схемы в итоговый КВО.

clear; clc;
load('falco_step12.mat', 'truth', 'imu', 'c');

fnav          = 250;       % выбранная частота навигатора [Гц] (кратна сетке 1000 Гц, step=4)
t_coast_start = 73.624;    % момент пропадания GNSS -> далее 60 с чистой ИНС [с]

fprintf('=== ШАГ 3: ПРЯМАЯ МЕХАНИЗАЦИЯ БИНС (ECEF) ===\n');

% ---------------------------------------------------------------------
% ТЕСТ 1: дрейф на полной траектории (диагностика, три частоты)
% ---------------------------------------------------------------------
fprintf('\n-- численный "пол" на ПОЛНОЙ траектории (диагностика) --\n');
for f = [100 250 400]
    nav  = ins_mechanize(imu, truth, c, f, 1);
    perr = pos_error(nav, truth);
    fprintf('  %3d Гц: ошибка позиции на ударе = %8.4f м\n', f, perr(end));
end

% ---------------------------------------------------------------------
% ТЕСТ 2: дрейф за 60 с коаста от поджатого GNSS состояния (релевантно)
% ---------------------------------------------------------------------
fprintf('\n-- "пол" за 60 с КОАСТА (старт из поджатого GNSS состояния) --\n');
a0 = round(t_coast_start/truth.dt) + 1;
for f = [100 250 400]
    nav  = ins_mechanize(imu, truth, c, f, a0);
    perr = pos_error(nav, truth);
    fprintf('  %3d Гц: пол коаста = %8.4f м\n', f, perr(end));
end

% ---------------------------------------------------------------------
% Прогон на выбранной частоте: считаем ОБЕ метрики явно
% ---------------------------------------------------------------------
% (1) Диагностика: полный дрейф от пуска без GNSS (НЕ репрезентативно для сценария,
%     т.к. в реальности GNSS гасит ошибку разгона до начала коаста).
nav_full  = ins_mechanize(imu, truth, c, fnav, 1);
perr_full = pos_error(nav_full, truth);

% (2) Релевантная метрика: чистый дрейф ИНС за 60 с коаста от GNSS-поджатого старта.
a0 = round(t_coast_start/truth.dt) + 1;
nav_coast  = ins_mechanize(imu, truth, c, fnav, a0);
perr_coast = pos_error(nav_coast, truth);

fprintf('\n=== ИТОГ на выбранной частоте %d Гц ===\n', fnav);
fprintf('  Диагностика (полный дрейф от пуска): %.4f м  <- НЕ метрика сценария\n', perr_full(end));
fprintf('  Релевантно (дрейф за 60 с коаста):   %.4f м  <- численный пол для КВО\n', perr_coast(end));

nav = nav_full;
save('falco_step3.mat', 'nav', 'fnav', 'truth', 'imu', 'c');
fprintf('сохранено: falco_step3.mat\n');


% =========================================================================
% ЛОКАЛЬНАЯ ФУНКЦИЯ: ошибка позиции навигатора относительно истины
% =========================================================================
function perr = pos_error(nav, truth)
%POS_ERROR  Модуль ошибки позиции на каждом такте навигатора.
%   Привязывает время тактов навигатора к отсчётам истины и считает |R_nav - R_truth|.
    idx  = round(nav.t/truth.dt) + 1;                 % индексы истины по времени тактов
    idx  = min(max(idx, 1), size(truth.R,1));         % защита от выхода за границы
    perr = vecnorm(nav.R - truth.R(idx,:), 2, 2);     % евклидова норма ошибки [м]
end