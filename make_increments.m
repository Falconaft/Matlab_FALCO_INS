function [a_idx, dtheta, dvel, dt_nav, step] = make_increments(imu, truth, fnav)
%MAKE_INCREMENTS  Интегрирует идеальные f^b и w_ib^b в приращения за такт навигации.
%   Берёт высокочастотные данные ИНС ("истину") и методом трапеций рассчитывает
%   инкременты угла dtheta = int(w_ib^b)dt и инкременты кажущейся скорости
%   dvel = int(f^b)dt для каждого такта навигатора. Это имитирует реальный IMU,
%   который выдаёт не мгновенные значения, а проинтегрированные за такт приращения.
%
%   ТРЕБОВАНИЕ КРАТНОСТИ ЧАСТОТ (fail-fast).
%   Частота истины ДОЛЖНА быть целократна частоте навигатора. Раньше функция
%   при некратных частотах ограничивалась предупреждением и продолжала работу
%   с округлённым step, из-за чего фактическая частота навигатора молча
%   отличалась от заявленной: при f_truth = 1000 Гц и fnav = 400 получалось
%   round(2.5) = 3, то есть реальные 333.3 Гц вместо 400. Такое расхождение
%   не видно в результатах и обесценивает сравнение режимов, поэтому теперь
%   выполнение ПРЕРЫВАЕТСЯ с диагностикой.
%
%   Входные параметры:
%     imu    - структура данных ИНС (imu.t, imu.wib_b, imu.fb)
%     truth  - структура истинной траектории (нужен шаг времени truth.dt)
%     fnav   - целевая частота навигатора [Гц]
%
%   Выходные параметры:
%     a_idx  - индексы начала каждого такта в исходных массивах (M x 1)
%     dtheta - приращения углов за такт (M x 3) [рад]
%     dvel   - приращения кажущейся скорости за такт (M x 3) [м/с]
%     dt_nav - период такта навигатора [с] (равен 1/fnav с точностью tolerance)
%     step   - число высокочастотных отсчётов в одном такте

    % =====================================================================
    % Шаг 1: ДИСКРЕТНОСТЬ И ПРОВЕРКА КРАТНОСТИ (FAIL-FAST)
    % =====================================================================
    dt_truth = truth.dt;                 % шаг истины (высокая частота)
    f_truth  = 1/dt_truth;               % частота истины [Гц]

    % Сколько отсчётов истины приходится на один такт навигатора
    ratio  = f_truth / fnav;
    step   = round(ratio);

    % Требуемый период такта навигатора и период, реализуемый на сетке истины
    dt_nav_req  = 1/fnav;
    dt_nav_grid = step * dt_truth;

    % Допуск: относительный, привязан к шагу истины. Величина 1e-9 на порядки
    % больше машинной точности double и на порядки меньше любого физически
    % значимого расхождения, поэтому ловит именно некратность, а не округление.
    tolerance = 1e-9 * dt_nav_req;

    % --- Проверка 1: отношение частот должно быть целым ---
    assert(abs(ratio - step) <= 1e-9 * max(1, ratio), ...
        'make_increments:nonIntegerRatio', ...
        ['Частота истины %.4f Гц НЕ КРАТНА частоте навигатора %.4f Гц.\n' ...
         'ratio = f_truth/f_nav = %.9f, ближайшее целое = %d.\n' ...
         'При продолжении фактическая частота навигатора составила бы %.4f Гц.\n' ...
         'Исправьте p.dt в traj_params.m или cfg.fnav в драйвере так, чтобы\n' ...
         'отношение было целым.'], ...
        f_truth, fnav, ratio, step, 1/(step*dt_truth));

    % --- Проверка 2: шаг такта на сетке истины совпадает с требуемым ---
    assert(abs(dt_nav_grid - dt_nav_req) <= tolerance, ...
        'make_increments:dtMismatch', ...
        ['Шаг такта на сетке истины не совпадает с требуемым.\n' ...
         'step*truth.dt = %.12f с, 1/f_nav = %.12f с, расхождение %.3e с\n' ...
         '(допуск %.3e с).'], ...
        dt_nav_grid, dt_nav_req, abs(dt_nav_grid - dt_nav_req), tolerance);

    % --- Проверка 3: минимум один отсчёт истины на такт ---
    assert(step >= 1, 'make_increments:stepTooSmall', ...
        ['Частота навигатора %.4f Гц выше частоты истины %.4f Гц ' ...
         '(step = %d < 1).'], fnav, f_truth, step);

    % Обе величины совпали в пределах допуска — берём точное значение
    dt_nav = dt_nav_grid;

    % =====================================================================
    % Шаг 2: РАЗМЕТКА ТАКТОВ
    % =====================================================================
    N = numel(imu.t);                    % полное число высокочастотных отсчётов

    % Индексы начала каждого навигационного интервала: 1, 1+step, 1+2*step, ...
    a_idx = (1:step:N-1)';

    % Отбрасываем последний такт, если он НЕПОЛНЫЙ (короче step интервалов).
    % Иначе на нём приращение пришло бы за меньшее время, чем фиксированный
    % dt_nav, что дало бы локальную ошибку скорости на самой последней точке.
    % Требуем, чтобы конец такта (a+step) не выходил за границу массива.
    a_idx = a_idx(a_idx + step <= N);
    M = numel(a_idx);                    % число ПОЛНЫХ тактов навигатора

    assert(M >= 1, 'make_increments:noFullTicks', ...
        ['Ни одного полного такта: отсчётов истины %d, step = %d.'], N, step);

    % Преаллокация выходных массивов (ускоряет работу MATLAB)
    dtheta = zeros(M,3);
    dvel   = zeros(M,3);

    % =====================================================================
    % Шаг 3: ЦИКЛ ИНТЕГРИРОВАНИЯ ПО ТАКТАМ НАВИГАЦИИ
    % =====================================================================
    for k = 1:M
        a = a_idx(k);                    % индекс начала текущего такта
        b = a + step;                    % индекс конца такта (ровно step интервалов)

        % Вырезаем сегменты высокочастотных данных и интегрируем по тактам:
        % интеграл угловой скорости -> приращение угла за такт
        dtheta(k,:) = trapz_dx(imu.wib_b(a:b,:), dt_truth);
        % интеграл кажущегося ускорения -> приращение кажущейся скорости за такт
        dvel(k,:)   = trapz_dx(imu.fb(a:b,:),    dt_truth);
    end
end


function I = trapz_dx(seg, dx)
%TRAPZ_DX  Численное интегрирование матрицы методом трапеций с шагом dx.
%   Вход:
%     seg - сегмент данных (строки - моменты времени, столбцы - оси X,Y,Z)
%     dx  - шаг интегрирования по времени
%   Выход:
%     I   - вектор интегралов по осям (1 x 3)
%
%   Формула трапеций в компактном виде:
%     Интеграл = dx * [ Сумма_всех_точек - 0.5*(первая + последняя) ]
%   sum(seg,1) суммирует по столбцам (для каждой оси отдельно).
    I = (sum(seg,1) - 0.5*(seg(1,:) + seg(end,:))) * dx;
end
