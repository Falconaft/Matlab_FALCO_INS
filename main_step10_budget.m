%% MAIN_STEP10_BUDGET  Шаг 10: бюджет ошибок для Pulse-40
%
%  Отвечает на вопрос: КАКОЙ источник ошибок доминирует и что улучшать.
%  Метод: базовая кампания + по одной кампании на каждый отключённый источник.
%
%  ВРЕМЯ. Источников 16, значит кампаний 17 (базовая + по одной на
%  источник). При фактических ~27 с/прогон:
%     N_mc = 10  ->  170 прогонов, ~1 ч 17 мин
%     N_mc = 20  ->  340 прогонов, ~2 ч 33 мин
%     N_mc = 25  ->  425 прогонов, ~3 ч 11 мин
%     N_mc = 50  ->  850 прогонов, ~6 ч 23 мин
%
%  ВЫБОР N. Сравнение ПАРНОЕ, поэтому чувствительность определяется СКО
%  парной разности, а не СКО выборки — оно существенно меньше. Ожидаемые
%  вклады B2 (~0.9 м) и B4 при 2 мс (~0.75 м) требуют N не менее 20-25;
%  при N = 10 они рискуют попасть в разряд незначимых.
%
%  Требует falco_step7.mat.

clear; clc; close all;
load('falco_step7.mat', 'truth', 'imu', 'c', 'p');

% =====================================================================
% Шаг 10.1: ПАРАМЕТРЫ
% =====================================================================
N_mc      = 50;          % парное сравнение; для B2/B4 нужно >= 20-25
base_seed = 7000;

% =====================================================================
% Шаг 10.2: КОНФИГУРАЦИЯ (та же, что в main_step9_mc)
% =====================================================================
% Базовая конфигурация; ниже — специфика бюджета ошибок.
cfg = falco_config();


cfg.sigma_pos  = 5*ones(3,1);    % СКО шума позиции GNSS [м]
cfg.sigma_vel  = 0.1*ones(3,1);   % СКО шума скорости GNSS [м/с]
% Частота записи диагностики задаётся ЯВНО в герцах, прореживание
% вычисляется из неё. Раньше стояло число 250, привязанное к f_nav=250
% (250 тактов = 1 с); при смене частоты навигатора смысл менялся бы молча.
cfg.f_diag     = 1;                                   % [Гц]
cfg.diag_decim = round(cfg.fnav / cfg.f_diag);   % пересчёт после смены f_diag
cfg.cep_target = 10;

t_end         = truth.t(end);
t_coast_start = t_end - p.coast_duration;
cfg.outage = [ 0.0            p.outage_boost_end;
               t_coast_start  t_end + 1.0 ];

cfg.align_sigma = [0.5e-3; 0.5e-3; 4.0e-3];
cfg.P0_att      = 1.3 * cfg.align_sigma;
% =====================================================================
% НАЧАЛЬНАЯ ОШИБКА ПОЗИЦИИ И СКОРОСТИ (предстартовое усреднение GNSS)
% =====================================================================
% Изделие перед пуском неподвижно, решение GNSS усредняется. Остаточная
% погрешность и есть начальная ошибка навигатора. Прежде навигатор
% стартовал ТОЧНО из истины, что занижало ошибку на начальном участке.
%
% СОГЛАСОВАННОСТЬ: P0 задаётся ТЕМИ ЖЕ величинами, что и фактическая
% ошибка. Фильтр знает ровно ту неопределённость, которая у него есть —
% не переуверен и не недоуверен.
%
% ВАЖНО: это НЕ шум измерений GNSS в полёте. cfg.sigma_pos и
% cfg.sigma_vel остаются без изменений.
cfg.init_pos_sigma = 1.0*ones(3,1);     % [м]   1-sigma после усреднения
cfg.init_vel_sigma = 0.03*ones(3,1);    % [м/с] 1-sigma
cfg.P0_pos = cfg.init_pos_sigma;
cfg.P0_vel = cfg.init_vel_sigma;
% ПРИМЕЧАНИЕ: прежде здесь стояло P0_pos = 3.0 м (сознательно ниже базовых
% 5.0 м). Теперь начальная модель ЕДИНАЯ со Шагом 9, поскольку она описывает
% физику предстартовой подготовки, а не настройку сценария. Специфичными
% для бюджета остаются только sigma_pos и sigma_vel (шум GNSS в полёте).

% =====================================================================
% BASELINE БЮДЖЕТА ВКЛЮЧАЕТ B2 И B4
% =====================================================================
% Оба источника входят в базовую конфигурацию и отключаются В БЮДЖЕТЕ
% наравне с остальными — их вклады измеряются тем же методом изоляции.
%
% B2: аномалия гравитационного поля, которую навигатор не знает.
cfg.defl_vert_sigma = 10 / 206265;      % [рад] СКО уклонения отвеса
cfg.grav_anom_sigma = 50e-5;            % [м/с²] СКО аномалии (50 мГал)

% B4: некомпенсированное рассогласование эпох GNSS/ИНС.
% 2 мс — реалистичная верхняя граница без аппаратной синхронизации по PPS.
cfg.gnss_time_offset_enable = true;
cfg.gnss_time_offset        = 2e-3;     % [с]

% =====================================================================
% Шаг 10.3: ПРОФИЛЬ И СЦЕНАРИЙ КАЛИБРОВКИ
% =====================================================================
prof = imu_profile_pulse40_updated();

% Раздельные коэффициенты калибровки (см. CAL_FACTOR_GUIDE.txt):
%   гироскоп калибруется до in-run пола (0.8/250 = 0.003)
%   акселерометр упирается в точность выставки по уровню
prof.cal_factor_gyro  = 0.003;   % гиро: остаток = in-run пол
prof.cal_factor_accel = 0.25;    % акс.: полевая выставка ~60 угл.сек
% Для сценария "без калибровки" поставь оба = 1.0

% =====================================================================
% ПРОВЕРКА ВРЕМЕННОЙ СЕТКИ (A1)
% =====================================================================
f_truth   = 1/truth.dt;
ratio_raw = f_truth / cfg.fnav;
step_chk  = round(ratio_raw);
dt_nav    = step_chk * truth.dt;
fnav_real = 1/dt_nav;
fprintf('=== ПРОВЕРКА ВРЕМЕННОЙ СЕТКИ (A1) ===\n');
fprintf('  запрошенная f_nav   : %10.4f Гц\n', cfg.fnav);
fprintf('  f_truth             : %10.4f Гц\n', f_truth);
fprintf('  ratio f_truth/f_nav : %10.6f\n',    ratio_raw);
fprintf('  step (отсчётов/такт): %10d\n',      step_chk);
fprintf('  dt_nav              : %10.6f с\n',  dt_nav);
fprintf('  ФАКТИЧЕСКАЯ f_nav   : %10.4f Гц\n', fnav_real);
fprintf('  ratio f_nav/f_gnss  : %10.4f\n',    cfg.fnav/cfg.f_gnss);
if abs(ratio_raw - step_chk) > 1e-12
    fprintf('  СТАТУС: НЕКРАТНЫЕ ЧАСТОТЫ — реально %.3f Гц вместо %.3f Гц!\n', ...
            fnav_real, cfg.fnav);
else
    fprintf('  СТАТУС: OK — частоты кратны, f_nav точная\n');
end
fprintf('\n');

fprintf('=== ШАГ 10: БЮДЖЕТ ОШИБОК ===\n');
fprintf('%s\n', repmat('*',1,64));
fprintf('*  BASELINE: B2 (аномалия гравитации) + B4 (сдвиг GNSS %.1f мс)   *\n', ...
        cfg.gnss_time_offset*1e3);
fprintf('*  Оба источника отключаются в бюджете наравне с остальными.     *\n');
fprintf('%s\n', repmat('*',1,64));
fprintf('Кандидат: %s\n', prof.name);
fprintf('Калибровка: гиро %.3f, акс. %.3f\n', ...
        prof.cal_factor_gyro, prof.cal_factor_accel);
fprintf('Реализаций на кампанию: %d\n', N_mc);
fprintf('%s\n', repmat('-',1,64));
fprintf('СОСТАВ BASELINE:\n');
fprintf('  B2 аномалия поля : уклонение отвеса %.1f", аномалия %.0f мГал\n', ...
        cfg.defl_vert_sigma*206265, cfg.grav_anom_sigma*1e5);
fprintf('  B4 сдвиг GNSS    : %.1f мс\n', cfg.gnss_time_offset*1e3);
fprintf('  шум GNSS в полёте: %.2f м / %.3f м/с при %.0f Гц\n', ...
        cfg.sigma_pos(1), cfg.sigma_vel(1), cfg.f_gnss);
fprintf('  нач. ошибка (СКО): %.2f м / %.3f м/с (предстартовое усреднение)\n', ...
        cfg.init_pos_sigma(1), cfg.init_vel_sigma(1));
fprintf('  выставка (СКО)   : курс %.1f мрад\n', cfg.align_sigma(3)*1e3);
fprintf('  плечо антенны    : [%.2f %.2f %.2f] м\n', cfg.lever);
fprintf('%s\n', repmat('-',1,64));
fprintf('ПАРНОСТЬ: все кампании используют base_seed = %d, поэтому\n', base_seed);
fprintf('реализации попарно сопоставимы и различаются только отключённым\n');
fprintf('источником.\n');
fprintf('%s\n', repmat('-',1,64));

% =====================================================================
% Шаг 10.4: ПРОГОН
% =====================================================================
budget = run_error_budget(prof, imu, truth, c, cfg, N_mc, base_seed);

% =====================================================================
% Шаг 10.5: ГРАФИКИ И СОХРАНЕНИЕ
% =====================================================================
plot_error_budget(budget);

save('falco_step10_budget.mat', 'budget', 'cfg', 'prof', 'N_mc', 'base_seed');
fprintf('\nсохранено: falco_step10_budget.mat\n');