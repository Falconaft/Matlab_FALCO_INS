function C = q2C(q)
%Q2C  Кватернион [w x y z] -> матрица поворота (body -> ECEF, т.е. C_e_b).
%   Стандартная формула преобразования кватерниона в матрицу направляющих косинусов.
%   Применение: вектор_в_ECEF = C * вектор_в_body.
    w = q(1);  x = q(2);  y = q(3);  z = q(4);
    C = [ 1-2*(y*y+z*z),  2*(x*y-w*z),    2*(x*z+w*y);
          2*(x*y+w*z),    1-2*(x*x+z*z),  2*(y*z-w*x);
          2*(x*z-w*y),    2*(y*z+w*x),    1-2*(x*x+y*y) ];
end
