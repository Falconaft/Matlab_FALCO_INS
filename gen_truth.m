function truth = gen_truth(cfg, c)
%GEN_TRUTH  Шаг 1: генерация идеальной "истинной" траектории центра масс в ECEF.
%
%   Строит непрерывную (класса C2) траекторию из двух участков:
%     - РАЗГОН    [0, t_b]      : аналитический профиль скорости (квинтик smoothstep),
%                                 у которого ускорение на обоих концах равно нулю
%                                 (a(0)=a(t_b)=0) -> нет скачка кажущейся силы на стыке.
%     - БАЛЛИСТИКА [t_b, удар]  : интегрирование уравнения свободного полёта в ECEF
%                                 методом Рунге-Кутты 4-го порядка (RK4).
%
%   Физический смысл: эта траектория - "эталон истины". Из неё на Шаге 2 обратной
%   механизацией синтезируются идеальные показания ИНС (акселерометр + гироскоп).
%
%   Входные параметры:
%     cfg - структура конфигурации сценария с полями:
%           lat0, lon0, h0 - геодезические координаты точки старта [рад, рад, м]
%           t_b            - длительность активного участка (разгона) [с]
%           v_up, v_h      - вертикальная (Up) и горизонтальная (East) компоненты
%                            скорости в конце разгона, заданные в ENU [м/с]
%           dt             - шаг интегрирования траектории (высокая частота) [с]
%           T              - максимальное время моделирования [с]
%     c   - структура физических констант WGS-84 (из constants.m)
%
%   Выходные параметры:
%     truth - структура с полями:
%             t  (N x 1) - вектор времени [с]
%             R  (N x 3) - позиция в ECEF [м]
%             V  (N x 3) - скорость в ECEF [м/с]
%             A  (N x 3) - КИНЕМАТИЧЕСКОЕ ускорение в ECEF (вторая производная r) [м/с^2]
%             r0, Cen    - позиция старта в ECEF и матрица ENU->ECEF
%             nb, dt     - индекс конца разгона и шаг времени
%             t_impact   - время падения [с]

    % =====================================================================
    % Шаг 1.1: ИНИЦИАЛИЗАЦИЯ ГЕОМЕТРИИ СТАРТА
    % =====================================================================
    r0  = lla2ecef(cfg.lat0, cfg.lon0, cfg.h0, c);  % позиция старта в ECEF [м]
    Cen = C_e_n(cfg.lat0, cfg.lon0);                % матрица перехода ENU -> ECEF

    % Целевой вектор скорости в конце разгона, заданный в локальной ENU:
    % [Восток; Север; Вверх]. Север = 0 -> разгон в плоскости Восток-Вверх.
    v_target_enu = [cfg.v_h; 0; cfg.v_up];

    % Дискретизация по времени
    dt = cfg.dt;
    N  = round(cfg.T/dt) + 1;        % полное число высокочастотных отсчётов
    nb = round(cfg.t_b/dt);          % индекс, на котором заканчивается разгон
    t  = (0:N-1)' * dt;              % вектор времени

    % Преаллокация массивов состояния (ускоряет работу MATLAB)
    R = zeros(N,3);   % позиция ECEF
    V = zeros(N,3);   % скорость ECEF
    A = zeros(N,3);   % кинематическое ускорение ECEF

    % =====================================================================
    % Шаг 1.2: УЧАСТОК РАЗГОНА (аналитический профиль smoothstep)
    % =====================================================================
    % Профиль скорости задаётся полиномом 5-й степени s(tau) = 10t^3-15t^4+6t^5,
    % где tau = t/t_b. Свойства: s(0)=0, s(1)=1, s'(0)=s'(1)=0.
    % Нулевая производная на концах гарантирует a(0)=a(t_b)=0 (гладкий старт/выход).
    for i = 1:nb+1
        tau = t(i)/cfg.t_b;

        s  = tau^3*(10 - 15*tau + 6*tau^2);          % smoothstep: профиль скорости
        sd = (tau^2*(30 - 60*tau + 30*tau^2))/cfg.t_b; % производная s по t (для ускорения)
        Is = cfg.t_b*(2.5*tau^4 - 3*tau^5 + tau^6);  % интеграл s по t (для позиции)

        % Проецируем профиль из ENU в ECEF и заполняем состояние
        V(i,:) = (Cen * (v_target_enu * s ))';       % скорость = v_target * s(tau)
        R(i,:) = (r0  + Cen * (v_target_enu * Is))';  % позиция  = r0 + v_target * Is
        A(i,:) = (Cen * (v_target_enu * sd))';        % ускорение = v_target * s'(tau)
    end

    % =====================================================================
    % Шаг 1.3: БАЛЛИСТИЧЕСКИЙ УЧАСТОК (RK4 свободного полёта в ECEF)
    % =====================================================================
    % Начальные условия берём со стыка с разгоном (узел nb+1).
    r = R(nb+1,:)';
    v = V(nb+1,:)';
    imp = N-1;   % индекс падения (по умолчанию - конец массива)

    for i = nb+1:N-1
        % --- Классический RK4 для системы [dr/dt = v; dv/dt = a_ball(r,v)] ---
        % Явная форма: на каждой стадии отдельно считаем наклон позиции (kNr)
        % и наклон скорости (kNv). Наклон позиции = скорость на данной стадии,
        % наклон скорости = баллистическое ускорение в пробной точке.

        % Стадия 1: в начале шага
        k1r = v;
        k1v = ballistic_acc(r, v, c);

        % Стадия 2: середина шага по наклонам стадии 1
        k2r = v + 0.5*dt*k1v;
        k2v = ballistic_acc(r + 0.5*dt*k1r, v + 0.5*dt*k1v, c);

        % Стадия 3: середина шага по наклонам стадии 2
        k3r = v + 0.5*dt*k2v;
        k3v = ballistic_acc(r + 0.5*dt*k2r, v + 0.5*dt*k2v, c);

        % Стадия 4: конец шага по наклонам стадии 3
        k4r = v + dt*k3v;
        k4v = ballistic_acc(r + dt*k3r, v + dt*k3v, c);

        % Взвешенное среднее наклонов (1+2+2+1)/6 -> обновление состояния.
        % ВАЖНО: все kNr, kNv уже посчитаны выше по старым (r,v), поэтому
        % порядок присваивания r и v безопасен.
        r = r + dt/6*(k1r + 2*k2r + 2*k3r + k4r);
        v = v + dt/6*(k1v + 2*k2v + 2*k3v + k4v);

        R(i+1,:) = r';
        V(i+1,:) = v';
        A(i+1,:) = ballistic_acc(r,v,c)';

        % Условие падения: высота над стартом стала отрицательной
        % ((r-r0) спроецированное на местную вертикаль Up = Cen(:,3))
        if ((r - r0)' * Cen(:,3) < 0) && (i > nb+100)
            imp = i+1;
            break;
        end
    end

    % =====================================================================
    % Шаг 1.4: ОБРЕЗКА МАССИВОВ ДО МОМЕНТА ПАДЕНИЯ И УПАКОВКА РЕЗУЛЬТАТА
    % =====================================================================
    R = R(1:imp,:);  V = V(1:imp,:);  A = A(1:imp,:);  t = t(1:imp);

    truth.t  = t;   truth.R = R;   truth.V = V;   truth.A = A;
    truth.r0 = r0;  truth.Cen = Cen;
    truth.nb = nb;  truth.dt = dt;
    truth.lat0 = cfg.lat0;  truth.lon0 = cfg.lon0;  truth.t_b = cfg.t_b;
    truth.t_impact = t(end);
end


function a = ballistic_acc(r, v, c)
%BALLISTIC_ACC  Кинематическое ускорение свободного полёта в ECEF.
%
%   Записано во ВРАЩАЮЩЕЙСЯ системе ECEF, поэтому помимо гравитации содержит
%   инерционные члены (Кориолис + центробежный):
%
%       a = g(r) - 2*[w_ie x]*v - [w_ie x]^2 * r
%
%   - g(r)            : гравитационное притяжение (gravitation, модель WGS-84 + J2)
%   - 2*[w_ie x]*v    : ускорение Кориолиса (из-за вращения Земли под телом)
%   - [w_ie x]^2 * r  : центробежное ускорение
%
%   ВАЖНО: g здесь - это чистое притяжение (gravitation), БЕЗ центробежной части.
%   Центробежный член вынесен отдельно. Это разделение критично для ECEF и
%   отличается от NED-механизации, где центробежное "спрятано" в gravity.
    WIEx = skew(c.WIE);                       % кососимметричная матрица w_ie
    a = grav_ecef(r,c) - 2*WIEx*v - WIEx*(WIEx*r);
end