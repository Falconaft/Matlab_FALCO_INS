%% MAIN_STEP6  Шаг 6: Монте-Карло кампания ESKF для кандидата Pulse-40
%
%  Оценка НАСТОЯЩЕГО КВО: N независимых реализаций полного контура
%  ИНС + GNSS + ESKF с разыгрыванием всех источников случайности.
%
%  Отличие от Шага 4 (run_montecarlo_coast): там была чистая ИНС без
%  фильтра (пессимистичная граница), здесь работает весь контур -
%  фильтр оценивает bias по GNSS, и результат отражает реальную систему.
%
%  Требует falco_step12.mat.

clear; clc; close all;
load('falco_step12.mat', 'truth', 'imu', 'c');

% =====================================================================
% Шаг 6.1: ПАРАМЕТРЫ КАМПАНИИ
% =====================================================================
N_mc      = 25;         % число реализаций (250 -> ~35 мин; для пробы ставь 20-30)
base_seed = 2000;        % базовый seed: одна и та же кампания воспроизводится
cep_target = 10;         % целевой КВО [м]

% =====================================================================
% Шаг 6.2: КОНФИГУРАЦИЯ ПРОГОНА (та же, что в main_step5)
% =====================================================================
cfg.fnav       = 250;              % частота навигатора [Гц]
cfg.f_gnss     = 10;                % частота GNSS [Гц]
cfg.sigma_pos  = 3*ones(3,1);    % СКО шума позиции GNSS [м]
cfg.sigma_vel  = 0.05*ones(3,1);   % СКО шума скорости GNSS [м/с]
cfg.corrtime   = 1000;             % время корреляции Гаусса-Маркова [с]
cfg.lever      = [0.1; 0.0; -0.1]; % плечо антенны GNSS от IMU в body [м]
% Прореживание диагностики: писать каждую N-ю точку вместо каждого такта.
% В Монте-Карло графики по времени не нужны (нужен только итог), поэтому
% 250 (= 1 Гц при такте 250 Гц) экономит память. На РЕЗУЛЬТАТ не влияет:
% итоговая ошибка берётся из последней точки, которая записывается всегда.
cfg.diag_decim = 250;
cfg.cep_target = cep_target;

% --- Окна аутэйджа GNSS ---
cfg.outage = [ 0.0   20.0;          % разгон: нет захвата первые 6 с
              40 200.0 ];      % терминальный коаст

% --- Начальная выставка ---
% align_sigma: РЕАЛЬНОЕ СКО ошибки выставки, разыгрывается на каждой реализации.
%   крен/тангаж от акселерометров (точно), курс от FOG-гирокомпаса.
%   4 mils (НАТО, 1/6400 окружности) ~ 3.9 мрад.
cfg.align_sigma = [1e-3; 1e-3; 8.0e-3];   % [рад] 1-sigma

% P0_att: что фильтр ДУМАЕТ о своей неопределённости ориентации.
% ВАЖНО: должно быть >= align_sigma, иначе фильтр переуверен и недооценивает
% собственную ошибку. Берём запас 1.3x и связываем автоматически, чтобы при
% смене align_sigma не забыть поправить P0_att.
cfg.P0_att      = 1.3 * cfg.align_sigma;      % [рад]

cfg.P0_pos      = [3.0; 3.0; 3.0];            % [м]
cfg.P0_vel      = [0.1; 0.1; 0.1];            % [м/с]

% =====================================================================
% Шаг 6.3: ПРОФИЛЬ КАНДИДАТА
% =====================================================================
prof = imu_profile_pulse40();

fprintf('=== ШАГ 6: МОНТЕ-КАРЛО КАМПАНИЯ ESKF ===\n');
fprintf('Кандидат: %s (диапазон акс. %d g)\n', prof.name, prof.accel.range_g);
fprintf('Реализаций: %d, базовый seed: %d\n', N_mc, base_seed);
fprintf('Выставка (СКО): крен/тангаж %.1f мрад, курс %.1f мрад\n', ...
        cfg.align_sigma(1)*1e3, cfg.align_sigma(3)*1e3);
fprintf('Аутэйдж GNSS: разгон %.1f-%.1f с, коаст с %.1f с\n', ...
        cfg.outage(1,1), cfg.outage(1,2), cfg.outage(2,1));
% КЛЮЧЕВОЙ параметр: сколько секунд GNSS остаётся ПЕРЕД коастом.
% Именно в этом окне фильтр оценивает bias, и от него КВО зависит сильнее,
% чем от длительности аутэйджа на разгоне.
fprintf('Окно GNSS перед коастом: %.1f с | длительность коаста: %.1f с\n\n', ...
        cfg.outage(2,1) - cfg.outage(1,2), truth.t(end) - cfg.outage(2,1));

% =====================================================================
% Шаг 6.4: ПРОГОН КАМПАНИИ
% =====================================================================
mc = run_montecarlo_eskf(prof, imu, truth, c, cfg, N_mc, base_seed);

% =====================================================================
% Шаг 6.5: ИТОГОВЫЕ МЕТРИКИ
% =====================================================================
g0 = 9.80665;
fprintf('\n=== РЕЗУЛЬТАТ: %s ===\n', mc.prof_name);
fprintf('%s\n', repmat('=',1,52));
fprintf('  КВО (медиана гориз. ошибки) : %8.2f м\n', mc.cep);
fprintf('  Среднее                     : %8.2f м\n', mc.mean_horiz);
fprintf('  СКО                         : %8.2f м\n', mc.std_horiz);
fprintf('  R95 (95%% процентиль)        : %8.2f м\n', mc.r95);
fprintf('  Худший прогон               : %8.2f м\n', mc.max_horiz);
fprintf('  Уложилось в %2.0f м            : %7.1f %%\n', cep_target, 100*mc.frac_pass);
fprintf('  Расходившихся прогонов      : %8d\n', mc.n_fail);
fprintf('%s\n', repmat('-',1,52));
fprintf('  Запас до цели по медиане    : %8.1fx\n', cep_target/mc.cep);
fprintf('  Систематика (ENU)           : [%+.2f %+.2f %+.2f] м\n', mc.bias_enu);
fprintf('  Оценка bias акс. (медиана)  : %7.1f %% от истинного\n', 100*mc.ba_frac_est);
fprintf('%s\n', repmat('=',1,52));

if mc.cep <= cep_target
    fprintf('\nВЕРДИКТ: кандидат %s ПРОХОДИТ по КВО (%.2f м <= %.0f м)\n', ...
            mc.prof_name, mc.cep, cep_target);
else
    fprintf('\nВЕРДИКТ: кандидат %s НЕ ПРОХОДИТ по КВО (%.2f м > %.0f м)\n', ...
            mc.prof_name, mc.cep, cep_target);
end

% =====================================================================
% Шаг 6.6: ГРАФИКИ
% =====================================================================
plot_montecarlo_cep(mc, cep_target);

save('falco_step6_mc.mat', 'mc', 'cfg', 'prof', 'N_mc', 'base_seed');
fprintf('\nсохранено: falco_step6_mc.mat\n');