function p = traj_params()
%TRAJ_PARAMS  Параметры реалистичной траектории (Шаг 7).
%
%   Профиль полёта: разгон -> отсечка двигателя -> перелом программы тангажа ->
%   апогей -> баллистика -> квазибаллистический спуск -> терминальный манёвр.
%
%   Все переключения программы угла атаки СГЛАЖЕНЫ (quintic smoothstep),
%   отсечка двигателя тоже — иначе разрывы удельной силы ломают синтез IMU.

    % =====================================================================
    % ТОЧКА СТАРТА И НАЦЕЛИВАНИЕ
    % =====================================================================
    p.lat0        = 50.4501;      % широта пусковой [град]
    p.lon0        = 30.5234;      % долгота пусковой [град]
    p.h0          = 150.0;        % высота пусковой [м]
    p.azimuth     = 80.0;         % азимут пуска [град] (0=север, 90=восток)
    p.launch_el   = 60.0;         % угол возвышения при пуске [град]
    p.impact_alt  = 120.0;        % высота, на которой считаем удар [м]
    p.V0          = 5.0;          % начальная скорость схода [м/с]

    % =====================================================================
    % МАССА И ДВИГАТЕЛЬ
    % =====================================================================
    p.m_control   = 20.0;         % масса блока управления [кг]
    p.m_warhead   = 60.0;         % масса БЧ [кг]
    p.m_casing    = 90.0;         % масса корпуса [кг]
    p.m_fuel      = 130.0;        % масса топлива [кг]
    p.isp         = 230.0;        % удельный импульс [с]
    p.t_burn      = 8.0;          % время работы двигателя [с]

    % =====================================================================
    % АЭРОДИНАМИКА
    % =====================================================================
    p.caliber     = 0.227;        % калибр [м]

    % =====================================================================
    % ПРОГРАММА УГЛА АТАКИ ПО ФАЗАМ
    %   фаза 1: разгон (alpha = 0)
    %   фаза 2: перелом программы тангажа (alpha = alpha_ph2) до theta_target
    %   фаза 3: после апогея, высота > h_switch (alpha = alpha_apogee)
    %   фаза 4: терминальный участок, высота < h_switch (alpha = alpha_low)
    % =====================================================================
    p.t_ph2       = 20.0;         % начало фазы 2 [с]
    p.alpha_ph2   = -6.0;         % угол атаки в фазе 2 [град]
    p.theta_target= 35.0;         % целевой угол наклона траектории [град]
    p.alpha_apogee=  7.0;         % угол атаки после апогея [град]
    p.h_switch    = 4000.0;       % высота перехода к терминальной фазе [м]
    p.alpha_low   = -7.0;         % угол атаки на терминальном участке [град]

    % =====================================================================
    % СГЛАЖИВАНИЕ ПЕРЕХОДОВ (критично для синтеза IMU!)
    % =====================================================================
    p.t_cutoff_smooth = 0.4;      % длительность спада тяги при отсечке [с]
    p.t_alpha_smooth  = 1.5;      % длительность перекладки угла атаки [с]

    % =====================================================================
    % ПРОГРАММА КРЕНА (изделие стабилизировано; колебания опционально)
    % =====================================================================
    p.roll_amp_deg  = 0.0;        % амплитуда колебаний крена [град] (0 = нет)
    p.roll_freq_hz  = 0.0;        % частота колебаний крена [Гц]

    % =====================================================================
    % СЕТКА ИНТЕГРИРОВАНИЯ
    % =====================================================================
    p.dt      = 0.001;            % шаг сетки истины [с] (1000 Гц)
    p.t_max   = 400.0;            % предохранитель по времени [с]

    % =====================================================================
    % СЦЕНАРИЙ GNSS (используется дальше в фильтре)
    % =====================================================================
    p.coast_duration   = 60;    % длительность терминального коаста [с]
    p.outage_boost_end = 6;     % конец аутэйджа на разгоне [с]

    % =====================================================================
    % ПРОИЗВОДНЫЕ ВЕЛИЧИНЫ
    % =====================================================================
    g0          = 9.80665;
    p.area      = pi*(p.caliber/2)^2;         % площадь миделя [м²]
    p.fuel_rate = p.m_fuel / p.t_burn;        % секундный расход [кг/с]
    p.thrust    = p.isp * g0 * p.fuel_rate;   % тяга [Н]
end
