function imu = inverse_mech(truth, c)
%INVERSE_MECH  Шаг 2: обратная механизация - синтез идеальных показаний ИНС.
%
%   Решает ОБРАТНУЮ задачу к механизации БИНС: зная истинную кинематику центра
%   масс (R, V, A из truth) и программу ориентации, вычисляет, что ДОЛЖНЫ были бы
%   показать идеальный акселерометр (кажущаяся сила f^b) и гироскоп (w_ib^b).
%
%   Ключевые формулы (всё в осях ECEF -> проекция в body):
%     f^b      = C_b_e * ( A - g(R) + 2*[w_ie x]*V + [w_ie x]^2 * R )
%     w_ib^b   = w_eb^b + C_b_e * w_ie
%   где C_b_e = (C_e_b)^T - матрица перехода ECEF -> body.
%
%   Программа ориентации (для варианта "б"):
%     - ось X тела направлена по местной вертикали Up в момент старта;
%     - на разгоне плавно (slerp) поворачивается к вектору скорости конца разгона;
%     - на баллистике ось X тела следует за вектором скорости (velocity-pointing).
%   Такая программа гладкая и не вырождается (нет особенности при |V|->0).
%
%   Вход:
%     truth - структура истинной траектории (из gen_truth)
%     c     - константы WGS-84
%   Выход:
%     imu - структура с полями:
%           t     (N x 1)   - время [с]
%           fb    (N x 3)   - кажущаяся сила в body [м/с^2]
%           wib_b (N x 3)   - абс. угловая скорость body отн. инерциальной [рад/с]
%           Ceb   (3 x 3 x N) - матрица body->ECEF (эталонная ориентация)

    % =====================================================================
    % Шаг 2.1: ПОДГОТОВКА
    % =====================================================================
    t = truth.t;  R = truth.R;  V = truth.V;  A = truth.A;
    Cen = truth.Cen;  nb = truth.nb;  dt = truth.dt;  N = numel(t);

    up      = Cen(:,3);                       % местная вертикаль Up в ECEF (старт)
    v_end   = V(nb+1,:)' / norm(V(nb+1,:));   % направление скорости в конце разгона
    ref_roll = Cen(:,2);                      % опорный вектор (местный Север) для крена

    % =====================================================================
    % Шаг 2.2: ПРОГРАММА ОРИЕНТАЦИИ -> направление оси X тела во времени
    % =====================================================================
    x_dir = zeros(N,3);
    for i = 1:N
        if t(i) <= truth.t_b
            % --- Разгон: плавный поворот от вертикали к вектору скорости ---
            tau = t(i)/truth.t_b;
            s   = tau^3*(10 - 15*tau + 6*tau^2);     % тот же smoothstep, что и в траектории
            x_dir(i,:) = slerp(up, v_end, s)';        % сферическая интерполяция направлений
        else
            % --- Баллистика: ось X тела вдоль вектора скорости ---
            v = V(i,:)';
            x_dir(i,:) = (v/norm(v))';
        end
        x_dir(i,:) = x_dir(i,:)/norm(x_dir(i,:));     % нормировка на всякий случай
    end

    % =====================================================================
    % Шаг 2.3: ПОСТРОЕНИЕ МАТРИЦ ОРИЕНТАЦИИ C_e_b (body -> ECEF)
    % =====================================================================
    Ceb = zeros(3,3,N);
    for i = 1:N
        Ceb(:,:,i) = make_frame(x_dir(i,:)', ref_roll);
    end

    % =====================================================================
    % Шаг 2.4: УГЛОВАЯ СКОРОСТЬ w_eb^b (body отн. ECEF) численным диффом
    % =====================================================================
    % Связь: dC_e_b/dt = C_e_b * [w_eb^b x]  =>  [w_eb^b x] = C_e_b^T * dC_e_b/dt
    % Производную C_e_b считаем центральной разностью по соседним узлам.
    w_eb_b = zeros(N,3);
    for i = 1:N
        im = max(i-1,1);  ip = min(i+1,N);
        Cdot = (Ceb(:,:,ip) - Ceb(:,:,im)) / ((ip-im)*dt);
        Wx = Ceb(:,:,i)' * Cdot;                  % кососимметричная матрица [w_eb^b x]
        w_eb_b(i,:) = [Wx(3,2), Wx(1,3), Wx(2,1)]; % извлекаем вектор (unskew)
    end

    % =====================================================================
    % Шаг 2.5: КАЖУЩАЯСЯ СИЛА f^b И ГИРОСКОП w_ib^b
    % =====================================================================
    fb    = zeros(N,3);
    wib_b = zeros(N,3);
    WIEx  = skew(c.WIE);

    for i = 1:N
        C_b_e = Ceb(:,:,i)';   % ECEF -> body

        % Кажущаяся сила: из полной механизации ECEF выражаем f^b.
        % Вычитаем гравитацию (акселерометр её НЕ чувствует) и добавляем
        % инерционные члены (Кориолис + центробежный), т.к. система вращается.
        f_E = A(i,:)' - grav_ecef(R(i,:)',c) ...
              + 2*WIEx*V(i,:)' + WIEx*(WIEx*R(i,:)');
        fb(i,:) = (C_b_e * f_E)';

        % Гироскоп измеряет АБСОЛЮТНУЮ скорость: к body-отн-ECEF добавляем
        % проекцию скорости вращения Земли w_ie на оси тела.
        wib_b(i,:) = w_eb_b(i,:) + (C_b_e * c.WIE)';
    end

    imu.t = t;  imu.fb = fb;  imu.wib_b = wib_b;  imu.Ceb = Ceb;
end


function C = make_frame(x_b, ref)
%MAKE_FRAME  Построение ортонормированного базиса body по заданной оси X.
%   Защита от вырождения (gimbal-lock): если ось X почти параллельна опорному
%   вектору ref, заменяем ref на другой, чтобы векторное произведение было устойчивым.
    if abs(x_b' * ref) > 0.95
        if abs(x_b(1)) < 0.9, ref = [1;0;0]; else, ref = [0;1;0]; end
    end
    y_b = cross(ref, x_b);  y_b = y_b/norm(y_b);   % ось Y тела
    z_b = cross(x_b, y_b);                          % ось Z тела (правая тройка)
    C = [x_b, y_b, z_b];                            % столбцы - оси тела в ECEF
end


function q = slerp(a, b, s)
%SLERP  Сферическая линейная интерполяция между двумя единичными векторами.
%   s in [0,1]: при s=0 возвращает a, при s=1 возвращает b.
%   Даёт поворот с постоянной угловой скоростью - гладкую программу ориентации.
    d = max(min(a'*b, 1), -1);   % косинус угла (с защитой от выхода за [-1,1])
    th = acos(d);                % угол между векторами
    if th < 1e-6
        q = a;                   % векторы почти совпали - интерполяция не нужна
    else
        q = (sin((1-s)*th)*a + sin(s*th)*b)/sin(th);
    end
end
