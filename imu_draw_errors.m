function e = imu_draw_errors(profile, rng_stream)
%IMU_DRAW_ERRORS  Розыгрыш ПОСТОЯННЫХ на полёт ошибок IMU (одна реализация МК).
%
%   Turn-on bias, масштабные коэффициенты и ошибка калибровки g-sensitivity —
%   это случайные КОНСТАНТЫ: разыгрываются один раз на экземпляр/запуск и
%   не меняются в течение полёта. In-run bias (Гаусс-Марков) эволюционирует
%   во времени отдельно, см. add_imu_errors.
%
%   Вход:
%     profile    - профиль IMU (из imu_profile_*.m)
%     rng_stream - поток случайных чисел (для воспроизводимости МК)
%   Выход:
%     e - структура реализации:
%         gyro_turnon_bias  (3x1) [рад/с]
%         accel_turnon_bias (3x1) [м/с²]
%         gyro_scale        (3x1) [-]
%         accel_scale       (3x1) [-]
%         g_sens_cal_err    (3x1) [-]  относительная ошибка калибровки g-sens

    % =====================================================================
    % ДОЛЯ turn-on bias ПОСЛЕ ПРЕДПУСКОВОЙ КАЛИБРОВКИ
    % =====================================================================
    % Физика калибровки РАЗНАЯ для гироскопа и акселерометра:
    %   гироскоп     - в статике показывает только вращение Земли, bias
    %                  оценивается усреднением; предел = in-run пол
    %                  (для Pulse-40 достижимо ~0.003);
    %   акселерометр - всегда чувствует g, bias НЕ отделим от наклона без
    %                  внешнего эталона вертикали; предел задаёт точность
    %                  выставки по уровню (0.02..0.23 в зависимости от неё).
    % Поэтому допускаются РАЗДЕЛЬНЫЕ коэффициенты. Если они не заданы,
    % используется общий cal_factor (обратная совместимость).
    if isfield(profile, 'cal_factor_gyro')
        cal_g = profile.cal_factor_gyro;
    else
        cal_g = profile.cal_factor;
    end
    if isfield(profile, 'cal_factor_accel')
        cal_a = profile.cal_factor_accel;
    else
        cal_a = profile.cal_factor;
    end

    % =====================================================================
    % TURN-ON BIAS: случайная константа на запуск
    % =====================================================================
    e.gyro_turnon_bias  = cal_g * profile.gyro.turnon_bias_sigma  * randn(rng_stream, 3, 1);
    e.accel_turnon_bias = cal_a * profile.accel.turnon_bias_sigma * randn(rng_stream, 3, 1);

    % =====================================================================
    % SCALE FACTOR: случайная константа на полёт
    % =====================================================================
    e.gyro_scale  = profile.gyro.scale_factor_sigma  * randn(rng_stream, 3, 1);
    e.accel_scale = profile.accel.scale_factor_sigma * randn(rng_stream, 3, 1);

    % =====================================================================
    % ПЕРЕКОС ОСЕЙ И НЕОРТОГОНАЛЬНОСТЬ (случайные константы экземпляра)
    % =====================================================================
    % Два РАЗНЫХ физических эффекта, в datasheet — два разных параметра:
    %   misalign_axes  — вся триада повёрнута относительно корпуса
    %                    (datasheet: Misalignment, у Pulse-40 1 мрад);
    %   misalign_ortho — оси внутри триады не строго перпендикулярны
    %                    (datasheet: Orthogonality, у Pulse-40 0.07 мрад).
    % Оба дают ВНЕДИАГОНАЛЬНЫЕ члены матрицы ошибок: сила вдоль X порождает
    % паразитное показание по Y и Z. Фильтр их НЕ оценивает (в состоянии
    % только диагональный масштаб), поэтому это неучтённая ошибка.
    e.accel_misalign = draw_field(profile.accel, 'misalign_axes',  rng_stream);
    e.gyro_misalign  = draw_field(profile.gyro,  'misalign_axes',  rng_stream);
    e.accel_ortho    = draw_field(profile.accel, 'misalign_ortho', rng_stream);
    e.gyro_ortho     = draw_field(profile.gyro,  'misalign_ortho', rng_stream);

    % =====================================================================
    % ВИБРАЦИОННЫЙ РЕКТИФИКАЦИОННЫЙ КОЭФФИЦИЕНТ (VRC)
    % =====================================================================
    % Под вибрацией нелинейность датчика выпрямляет знакопеременный сигнал и
    % создаёт ложное ПОСТОЯННОЕ смещение, пропорциональное КВАДРАТУ уровня
    % вибрации:  |b_vrc| ~ VRC * g_rms^2.
    %
    % ЧТО ДАЁТ DATASHEET: только МОДУЛЬ коэффициента (Pulse-40: 0.03 мg/g^2
    % для акселерометра, 0.03 °/ч/g^2 для гироскопа). Знак и распределение
    % по осям НЕ СПЕЦИФИЦИРОВАНЫ — они зависят от вида нелинейности
    % конкретного экземпляра и от направления вибрации.
    %
    % ДОПУЩЕНИЕ (не из datasheet, обозначено явно):
    %   смещение по каждой оси моделируется как нормальная случайная величина
    %   с нулевым средним и СКО = VRC * g_rms^2, разыгрываемая ОДИН РАЗ на
    %   экземпляр и постоянная в течение полёта.
    %
    % ПОЧЕМУ НЕ КОНСТАНТА ОДНОГО ЗНАКА: детерминированное смещение по всем
    % трём осям давало бы одинаковый по знаку снос во ВСЕХ реализациях
    % Монте-Карло, то есть искусственную систематику по ансамблю. Физически
    % же знак нелинейности случаен от экземпляра к экземпляру.
    e.accel_vrc_dir = randn(rng_stream, 3, 1);   % безразмерные множители,
    e.gyro_vrc_dir  = randn(rng_stream, 3, 1);   % масштабируются в add_imu_errors

    % =====================================================================
    % ОШИБКА КАЛИБРОВКИ g-SENSITIVITY
    % =====================================================================
    % Коэффициент g-чувствительности гироскопа измеряется на центрифуге при
    % приёмке, и механизация компенсирует его ПАСПОРТНЫМ значением Gg_nom.
    % Реальный экземпляр имеет Gg_true = Gg_nom*(1 + d), где d — относительная
    % ошибка калибровки. Нескомпенсированный остаток Gg_nom*d*f и есть
    % источник ошибки.
    %
    % ВАЖНО: d разыгрывается СЛУЧАЙНО на каждый экземпляр, поэтому по
    % ансамблю Монте-Карло систематика отсутствует. Если бы остаток был
    % детерминированным (просто доля от номинала), он давал бы одинаковый
    % по знаку боковой снос во всех реализациях — что и наблюдалось,
    % пока компенсации не было вовсе.
    if isfield(profile.gyro, 'g_sens_cal_sigma')
        e.g_sens_cal_err = profile.gyro.g_sens_cal_sigma * randn(rng_stream, 3, 1);
    else
        e.g_sens_cal_err = zeros(3,1);      % совместимость со старыми профилями
    end
end


function v = draw_field(sensor, fieldname, rng_stream)
%DRAW_FIELD  Розыгрыш 3x1 вектора по СКО из поля профиля (0, если поля нет).
%   Обратная совместимость: старые профили без новых полей работают как раньше.
    if isfield(sensor, fieldname)
        v = sensor.(fieldname) * randn(rng_stream, 3, 1);
    else
        v = zeros(3,1);
    end
end