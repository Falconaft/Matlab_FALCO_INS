function [rho, a_sound, T, P] = atmosphere_isa(h)
%ATMOSPHERE_ISA  Стандартная атмосфера ISA до 32 км.
%
%   Три слоя: тропосфера (линейный градиент), тропопауза (изотерма),
%   нижняя стратосфера (инверсия). Выше 32 км модель не используется —
%   наш апогей ~20 км.
%
%   Вход:  h       - геометрическая высота [м]
%   Выход: rho     - плотность [кг/м³]
%          a_sound - скорость звука [м/с]
%          T       - температура [К]
%          P       - давление [Па]

    R_air = 287.05287;      % удельная газовая постоянная воздуха [Дж/(кг·К)]
    gamma = 1.4;            % показатель адиабаты

    h_calc = max(0.0, h);

    if h_calc < 11000
        % Тропосфера: градиент -6.5 К/км
        T = 288.15 - 0.0065*h_calc;
        P = 101325 * (T/288.15)^5.25588;
    elseif h_calc < 20000
        % Тропопауза: изотермический слой
        T = 216.65;
        P = 22632 * exp(-0.000157688*(h_calc - 11000));
    else
        % Нижняя стратосфера: градиент +1.0 К/км
        T = 216.65 + 0.001*(h_calc - 20000);
        P = 5474.89 * (216.65/T)^34.16319;
    end

    rho     = P / (R_air * T);
    a_sound = sqrt(gamma * R_air * T);
end
