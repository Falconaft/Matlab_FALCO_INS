function PHI = eskf_discretize(F, dt, order)
%ESKF_DISCRETIZE  Дискретная матрица перехода Φ из непрерывной F.
%
%   Строит Φ = exp(F·dt) через усечённый ряд Тейлора матричной экспоненты
%   (Sandia: Φ = e^{A·Δt}). Порядок ряда выбирается параметром.
%
%   ВАЖНО: Φ дискретизирует ТОЛЬКО распространение ковариации P
%   (P_{k+1} = Φ·P·Φ' + Qd). Само состояние (r,v,q) считается ТОЧНОЙ
%   нелинейной механизацией (ins_mechanize, RK4), НЕ через Φ. Поэтому
%   ошибка усечения ряда влияет на оценку неопределённости, но не на траекторию.
%
%   Выбор порядка (проверено численно на dt=1/250):
%     1-й порядок (I+FΔt):      ошибка ~9e-4  (KF-GINS использует этот)
%     2-й порядок (+½(FΔt)²):   ошибка ~8e-7  (наш выбор: баланс точность/цена)
%     3-й порядок (+⅙(FΔt)³):   ошибка ~8e-13 (машинный ноль, избыточно)
%   2-й порядок нужен из-за сильной связи δr<->δv (двойное интегрирование за такт):
%   1-й порядок теряет перекрёстные блоки Φ[δr,δψ], Φ[δv,δbg] и т.п.
%
%   Вход:
%     F     - непрерывная матрица динамики ошибок (21x21) [1/с]
%     dt    - шаг времени [с]
%     order - порядок ряда (1, 2 или 3; по умолчанию 2)
%   Выход:
%     PHI   - дискретная матрица перехода (21x21)

    if nargin < 3 || isempty(order)
        order = 2;    % по умолчанию 2-й порядок (наш выбор)
    end

    n = size(F, 1);
    FDT = F * dt;              % безразмерная матрица F·Δt

    % Ряд Тейлора матричной экспоненты: Φ = I + FΔt + (FΔt)²/2! + ...
    PHI = eye(n);              % нулевой член: I
    term = eye(n);             % текущий член ряда (начинаем с I)

    for k = 1:order
        term = term * FDT / k; % (FΔt)^k / k!  (рекуррентно из предыдущего)
        PHI = PHI + term;
    end

    % Примечание: для максимальной точности можно заменить на expm(FDT),
    % но усечённый ряд дешевле и детерминированнее для встраиваемой реализации.
end
