function F = eskf_F_matrix(r_e, v_e, C_b_e, f_b, w_ib_b, c, corrtime, Gg, f_thresh)
%ESKF_F_MATRIX  Матрица динамики ошибок (continuous-time) 21-состояния ESKF в ECEF.
%
%   Строит матрицу F непрерывной error-state динамики δẋ = F·δx + G·w
%   по выводу Sandia (eq. 7.38-7.42) с конвенцией глобальной ошибки Solà
%   (left-multiplication) и error-of-estimate (bias/scale вычитаются из измерений).
%
%   Порядок состояния (21 = 7 блоков по 3):
%     δx = [δr; δv; δψ; δbg; δba; δsg; δsa]
%          позиция, скорость, ориентация, bias гиро, bias акс, scale гиро, scale акс
%
%   Все ненулевые блоки (по Sandia 7.38-7.42, с нашими знаками):
%     F[δr, δv]  = I₃                                    (7.38, кинематика)
%     F[δv, δr]  = -μ/r³·I + 3μ/r⁵·rr' - [ω_ie×]²        (7.39, гравиградиент+центробеж)
%     F[δv, δv]  = -2[ω_ie×]                             (7.39, Кориолис)
%     F[δv, δψ]  = -[C_b_e·f_b ×]                        (7.39, проекция удельной силы)
%     F[δv, δba] = -C_b_e                                (7.39, bias акселерометра)
%     F[δv, δsa] = -C_b_e·diag(f_b)                      (7.39, scale акселерометра)
%     F[δψ, δψ]  = -[ω_ie×]                              (7.40, вращение Земли, GLOBAL)
%     F[δψ, δbg] = -C_b_e                                (7.40, bias гироскопа)
%     F[δψ, δsg] = -C_b_e·diag(w_ib_b)                   (7.40, scale гироскопа)
%     F[δψ, δbg]+= -C_b_e·Gg·[...]  (опц., g-sens, только при |f_b|>f_thresh)
%     F[δbg,δbg] = -1/corrtime·I    (Гаусс-Марков, ОТХОД от Sandia RW, ~KF-GINS)
%     F[δba,δba] = -1/corrtime·I
%     F[δsg,δsg] = 0, F[δsa,δsa] = 0  (scale = случайная константа: проявляется
%                                      только на 10с разгона, дрейф ничтожен)
%
%   Вход:
%     r_e      - позиция ECEF (3x1) [м]
%     v_e      - скорость ECEF (3x1) [м/с]
%     C_b_e    - матрица ориентации body->ECEF (3x3)
%     f_b      - удельная сила в body (3x1) [м/с²]
%     w_ib_b   - угловая скорость body-отн-инерц в body (3x1) [рад/с]
%     c        - структура констант (c.WIE, c.MU, c.A_E, c.J2)
%     corrtime - время корреляции Гаусса-Маркова [с]
%     Gg       - матрица g-sensitivity гироскопа (3x3) [(рад/с)/(м/с²)], опц.
%     f_thresh - порог |f_b| для включения g-sens в F [м/с²], опц.
%   Выход:
%     F        - матрица динамики ошибок (21x21) [непрерывное время]

    % Значения по умолчанию для опциональных аргументов
    if nargin < 8 || isempty(Gg),        Gg = zeros(3);   end
    if nargin < 9 || isempty(f_thresh),  f_thresh = 1e9;  end  % по умолч. g-sens выкл

    % Индексы блоков состояния
    ir  = 1:3;    % δr
    iv  = 4:6;    % δv
    ip  = 7:9;    % δψ
    ibg = 10:12;  % δbg
    iba = 13:15;  % δba
    isg = 16:18;  % δsg
    isa = 19:21;  % δsa

    F = zeros(21,21);

    % Кососимметричная матрица вращения Земли
    WIE  = c.WIE;
    WIEx = skew(WIE);

    % =====================================================================
    % Шаг 5.x.1: строка δr (позиция) - Sandia 7.38
    % =====================================================================
    F(ir, iv) = eye(3);

    % =====================================================================
    % Шаг 5.x.2: строка δv (скорость) - Sandia 7.39
    % =====================================================================
    % Гравитационный градиент (ньютоновская часть; J₂-часть опущена как
    % численно пренебрежимая - проверено ~0.9мм за коаст)
    r_norm = norm(r_e);
    G_grad = -c.MU/r_norm^3 * eye(3) + 3*c.MU/r_norm^5 * (r_e * r_e');

    % Блок F[δv,δr]: гравиградиент + производная центробежного члена
    F(iv, ir) = G_grad - WIEx*WIEx;

    % Блок F[δv,δv]: Кориолис
    F(iv, iv) = -2*WIEx;

    % Блок F[δv,δψ]: проекция удельной силы (знак минус, global/Solà)
    f_e = C_b_e * f_b;                 % удельная сила в ECEF
    F(iv, ip) = -skew(f_e);

    % Блок F[δv,δba]: bias акселерометра (минус, error-of-estimate)
    F(iv, iba) = -C_b_e;

    % Блок F[δv,δsa]: scale акселерометра
    F(iv, isa) = -C_b_e * diag(f_b);

    % =====================================================================
    % Шаг 5.x.3: строка δψ (ориентация) - Sandia 7.40, GLOBAL convention
    % =====================================================================
    % Блок F[δψ,δψ]: вращение Земли (ТОЛЬКО ω_ie, не ω_ib - признак global!)
    F(ip, ip) = -WIEx;

    % Блок F[δψ,δbg]: bias гироскопа
    F(ip, ibg) = -C_b_e;

    % Блок F[δψ,δsg]: scale гироскопа
    F(ip, isg) = -C_b_e * diag(w_ib_b);

    % Опциональная g-sensitivity: включаем только на большой удельной силе (разгон).
    % На коасте |f_b|≈0 -> член выключен (экономия и корректность).
    if norm(f_b) > f_thresh
        % g-sens связывает δψ с ошибкой удельной силы через gyro; вклад в блок δba
        % (упрощённая изотропная модель: -C·Gg действует на δf, δf~δba канал)
        F(ip, iba) = F(ip, iba) - C_b_e * Gg;
    end

    % =====================================================================
    % Шаг 5.x.4: строки bias (Гаусс-Марков) - ОТХОД от Sandia 7.41-42 (RW)
    % =====================================================================
    F(ibg, ibg) = -1/corrtime * eye(3);
    F(iba, iba) = -1/corrtime * eye(3);
    % F(ibg, ibg) = zeros(3);
    % F(iba, iba) = zeros(3);


    % =====================================================================
    % Шаг 5.x.5: строки scale (RANDOM CONSTANT - случайная константа на полёт)
    % =====================================================================
    % ОБОСНОВАНИЕ (через анализ наблюдаемости):
    % Scale factor проявляется только при большой удельной силе/вращении, т.е.
    % ТОЛЬКО на 10с разгона (на коасте f≈0, ω≈0 -> scale не проявляется).
    % За эти 10с тепловой дрейф scale ничтожен -> scale = КОНСТАНТА на активном
    % участке. GM-модель здесь избыточна (нечего "переоценивать" за 10с).
    % Наблюдаемость: accel scale слабо отделим от bias (обусловленность ~5,
    % тяга на плато 17g), gyro scale почти ненаблюдаем. Поэтому scale держим как
    % случайную константу: F=0, Q=0, оценивается только через начальную P0.
    % F(isg,:) = 0, F(isa,:) = 0 - scale не эволюционирует.
end