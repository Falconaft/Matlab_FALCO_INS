function s = smoothstep5(x)
%SMOOTHSTEP5  Квинтическая функция сглаживания: C²-гладкий переход 0 -> 1.
%
%   s(x) = 10x³ - 15x⁴ + 6x⁵  на отрезке [0,1], зажата вне его.
%   Свойства: s(0)=0, s(1)=1, s'(0)=s'(1)=0, s''(0)=s''(1)=0.
%   Вторая производная непрерывна — поэтому нет скачков удельной силы,
%   которые ломали бы синтез показаний IMU.

    x = min(max(x, 0.0), 1.0);
    s = 10*x.^3 - 15*x.^4 + 6*x.^5;
end
