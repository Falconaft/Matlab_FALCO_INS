function g = grav_ecef(r, c)
%GRAV_ECEF  Гравитационное притяжение (gravitation) WGS-84 с учётом J2 в ECEF.
%
%   Возвращает ЧИСТОЕ ньютоновское притяжение + поправку сжатия J2 [м/с^2].
%   ВАЖНО: это gravitation, БЕЗ центробежной части - центробежный член входит
%   в механизацию отдельно (см. ballistic_acc / f_rv). Такое разделение
%   обязательно для ECEF и соответствует Sandia eq. 4.27.
%
%   Вход:  r - позиция в ECEF [м];  c - константы
%   Выход: g - вектор притяжения в ECEF [м/с^2]
    X = r(1);  Y = r(2);  Z = r(3);
    rn  = norm(r);                       % геоцентрический радиус
    fac = 1.5*c.J2*(c.A_E/rn)^2;         % безразмерный коэффициент при члене J2

    % Покомпонентная формула притяжения с J2. Для X,Y множитель (5Z^2/r^2 - 1),
    % для Z - (5Z^2/r^2 - 3): различие отражает осевую симметрию сжатия Земли.
    g = [ -c.MU/rn^3 * X * (1 - fac*(5*Z*Z/rn^2 - 1));
          -c.MU/rn^3 * Y * (1 - fac*(5*Z*Z/rn^2 - 1));
          -c.MU/rn^3 * Z * (1 - fac*(5*Z*Z/rn^2 - 3)) ];
end
