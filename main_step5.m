%% MAIN_STEP5  Шаг 5: полный прогон ESKF (ИНС + GNSS) с диагностикой
%
%  Один прогон интегрированной навигации на всей траектории:
%    - разгон 0-10 с (аутэйдж GNSS 0-6 с: приёмник не держит захват)
%    - GNSS активен 6-73.6 с
%    - терминальный коаст 73.6-133.6 с (аутэйдж - чистая ИНС)
%
%  Требует falco_step12.mat (truth + imu идеальный + константы).

clear; clc; close all;
load('falco_step12.mat', 'truth', 'imu', 'c');

% =====================================================================
% Шаг 5.12.1: КОНФИГУРАЦИЯ ПРОГОНА
% =====================================================================
cfg.fnav       = 250;              % частота навигатора [Гц]
cfg.f_gnss     = 10;                % частота GNSS [Гц]
cfg.sigma_pos  = 1.5*ones(3,1);    % СКО шума позиции GNSS [м]
cfg.sigma_vel  = 0.05*ones(3,1);   % СКО шума скорости GNSS [м/с]
cfg.corrtime   = 1000;             % время корреляции Гаусса-Маркова [с]
cfg.lever      = [0.1; 0.0; -0.1]; % плечо антенны GNSS от IMU в body [м]
cfg.seed       = 2024;
cfg.diag_decim = 25;               % диагностика с прореживанием (10 Гц)

% --- ОКНА АУТЭЙДЖА GNSS: [начало конец] в секундах ---
%   1) разгон 0-6 с: потеря захвата из-за динамики/факела
%   2) терминальный коаст с 73.6 с до удара
cfg.outage = [ 0.0   10.0;
              73.624 200.0 ];

% --- НАЧАЛЬНАЯ ВЫСТАВКА ---
% Ошибка выставки: крен/тангаж от акселерометров (точно), курс от FOG-гирокомпаса.
% 4 mils (НАТО) ~ 3.9 мрад по курсу.
cfg.align_err = [0.5e-3; 0.5e-3; 4.0e-3];   % [рад] ФАКТИЧЕСКАЯ ошибка
cfg.P0_att    = [1.0e-3; 1.0e-3; 5.0e-3];   % [рад] ЧЕСТНАЯ оценка неопределённости
cfg.P0_pos    = [3.0; 3.0; 3.0];            % [м]
cfg.P0_vel    = [0.1; 0.1; 0.1];            % [м/с]

% =====================================================================
% Шаг 5.12.2: ПРОФИЛЬ IMU И ГЕНЕРАЦИЯ ЗАШУМЛЁННЫХ ИЗМЕРЕНИЙ
% =====================================================================
prof = imu_profile_pulse40();      % МЕНЯЙ на другого кандидата при сравнении

rng_imu   = RandStream('mt19937ar','Seed', cfg.seed);
e_imu     = imu_draw_errors(prof, rng_imu);
imu_meas  = add_imu_errors(imu, prof, e_imu, rng_imu);

fprintf('=== ШАГ 5: ПОЛНЫЙ ПРОГОН ESKF ===\n');
fprintf('Профиль IMU: %s\n', prof.name);
fprintf('Истинный turn-on bias: гиро %.2f °/ч, акс %.2f мг\n', ...
        norm(e_imu.gyro_turnon_bias)/(pi/180)*3600, ...
        norm(e_imu.accel_turnon_bias)/9.80665*1e3);
fprintf('Ошибка выставки: крен/тангаж %.1f мрад, курс %.1f мрад\n', ...
        cfg.align_err(1)*1e3, cfg.align_err(3)*1e3);
fprintf('Аутэйдж GNSS: разгон %.1f-%.1f с, коаст с %.1f с\n\n', ...
        cfg.outage(1,1), cfg.outage(1,2), cfg.outage(2,1));

% =====================================================================
% Шаг 5.12.3: ПРОГОН ФИЛЬТРА
% =====================================================================
tic;
res = eskf_run(imu_meas, truth, c, prof, cfg);
fprintf('Прогон завершён за %.1f с\n\n', toc);

% =====================================================================
% Шаг 5.12.4: КЛЮЧЕВЫЕ МЕТРИКИ В КОНСОЛЬ
% =====================================================================
t_marks = [cfg.outage(1,2), 10.0, cfg.outage(2,1)-0.1, res.t(end)];
lbl     = {'конец аутэйджа разгона','конец разгона','перед потерей GNSS','удар'};
fprintf('%-24s %10s %10s %12s\n','Момент','|dr|, м','|dv|, м/с','|dpsi|, мрад');
fprintf('%s\n', repmat('-',1,60));
for i = 1:numel(t_marks)
    [~, k] = min(abs(res.t - t_marks(i)));
    fprintf('%-24s %10.2f %10.3f %12.3f\n', lbl{i}, ...
            norm(res.dr(k,:)), norm(res.dv(k,:)), norm(res.dpsi(k,:))*1e3);
end
fprintf('%s\n', repmat('-',1,60));
fprintf('\nГоризонтальная ошибка на ударе (метрика КВО): %.2f м\n', res.err_horiz_final);
fprintf('Полная 3D-ошибка на ударе:                    %.2f м\n', res.err_3d_final);

g0 = 9.80665;
fprintf('\nОценка bias акселерометра [мг]: %s\n', mat2str(res.nav.ba'/g0*1e3, 4));
fprintf('Истинный bias акселерометра [мг]: %s\n', mat2str(e_imu.accel_turnon_bias'/g0*1e3, 4));
fprintf('Остаточная ошибка bias: %.3f мг из %.3f мг (оценено %.1f%%)\n', ...
        norm(e_imu.accel_turnon_bias - res.nav.ba)/g0*1e3, ...
        norm(e_imu.accel_turnon_bias)/g0*1e3, ...
        100*(1 - norm(e_imu.accel_turnon_bias - res.nav.ba)/norm(e_imu.accel_turnon_bias)));

% =====================================================================
% Шаг 5.12.5: ГРАФИКИ
% =====================================================================
%plot_eskf_results(res, truth, e_imu.accel_turnon_bias, e_imu.gyro_turnon_bias);

save('falco_step5.mat', 'res', 'cfg', 'prof');
fprintf('\nсохранено: falco_step5.mat\n');
