function [H, R] = eskf_H_gnss(sigma_pos, sigma_vel, use_vel, C_b_e, w_ib_b, lever, c)
%ESKF_H_GNSS  Матрица измерений H и ковариация R для GNSS (позиция+скорость ECEF)
%             С ПОЛНЫМ УЧЁТОМ LEVER ARM (вынос антенны от IMU).
%
%   GNSS измеряет позицию/скорость АНТЕННЫ, вынесенной на плечо l^b от IMU:
%     r_ant = r_IMU + C_b_e·l^b
%     v_ant = v_IMU + C_b_e·(ω_ib^b × l^b) + [ω_ie×]·(C_b_e·l^b)
%   Ошибки состояния (δψ, δbg, δsg) через плечо влияют на измерение -> H имеет
%   дополнительные блоки во 2-й строке (скорость). Для высокодинамичных объектов
%   (ракета) эти члены строго обязательны (в отличие от авто, где их опускают).
%
%   ВСЕ ЗНАКИ проверены численно (конечно-разностный якобиан) в нашей конвенции
%   (global/left ошибка ориентации + error-of-estimate). Знаки отличаются от
%   типовых "автомобильных" выводов - там другая конвенция.
%
%   Структура H (6x21):
%     Строка позиции:
%       H[поз, δr]  = I₃
%       H[поз, δψ]  = -[(C_b_e·l)×]                    (плечо разворачивается δψ)
%     Строка скорости:
%       H[скор, δv]  = I₃
%       H[скор, δψ]  = -[(C_b_e(ω_ib×l))×] - [ω_ie×][(C_b_e·l)×]   (H_vψ)
%       H[скор, δbg] = +C_b_e·[l×]                     (bias гиро через ω×l)
%       H[скор, δsg] = +C_b_e·[l×]·diag(ω_ib)          (scale гиро через ω×l)
%
%   Вход:
%     sigma_pos - СКО шума позиции GNSS [м] (скаляр или 3x1)
%     sigma_vel - СКО шума скорости GNSS [м/с] (скаляр или 3x1)
%     use_vel   - использовать скорость GNSS (true -> 6 изм., false -> 3)
%     C_b_e     - ориентация body->ECEF (3x3)
%     w_ib_b    - угловая скорость body-отн-инерц (3x1) [рад/с]
%     lever     - плечо антенны от IMU в body (3x1) [м]
%     c         - константы (c.WIE)
%   Выход:
%     H - матрица измерений (6x21 или 3x21)
%     R - ковариация шума измерений (6x6 или 3x3)

    if nargin < 3 || isempty(use_vel), use_vel = true;       end
    if nargin < 6 || isempty(lever),   lever   = zeros(3,1); end

    RANK = 21;
    ir  = 1:3;    iv  = 4:6;    ip  = 7:9;
    ibg = 10:12;  iba = 13:15;  isg = 16:18;  isa = 19:21;

    if isscalar(sigma_pos), sigma_pos = sigma_pos*ones(3,1); end
    if isscalar(sigma_vel), sigma_vel = sigma_vel*ones(3,1); end

    % Вектор плеча в ECEF и его кососимметричная матрица
    Cl    = C_b_e * lever;          % плечо в ECEF
    Cl_x  = skew(Cl);               % [(C·l)×]
    WIEx  = skew(c.WIE);

    if use_vel
        % =================================================================
        % GNSS позиция + скорость (6 измерений)
        % =================================================================
        H = zeros(6, RANK);

        % --- Строка позиции ---
        H(1:3, ir) = eye(3);
        if any(lever ~= 0)
            H(1:3, ip) = -Cl_x;                    % H[поз,δψ] = -[(C·l)×]
        end

        % --- Строка скорости ---
        H(4:6, iv) = eye(3);
        if any(lever ~= 0)
            % H_vψ = -[(C(ω×l))×] - [ω_ie×][(C·l)×]
            Cwl = C_b_e * cross(w_ib_b, lever);
            H(4:6, ip)  = -skew(Cwl) - WIEx * Cl_x;
            % H[скор,δbg] = +C·[l×]
            H(4:6, ibg) = C_b_e * skew(lever);
            % H[скор,δsg] = +C·[l×]·diag(ω_ib)
            H(4:6, isg) = C_b_e * skew(lever) * diag(w_ib_b);
        end

        R = diag([sigma_pos(:).^2; sigma_vel(:).^2]);
    else
        % =================================================================
        % Только GNSS позиция (3 измерения)
        % =================================================================
        H = zeros(3, RANK);
        H(1:3, ir) = eye(3);
        if any(lever ~= 0)
            H(1:3, ip) = -Cl_x;
        end
        R = diag(sigma_pos(:).^2);
    end
end