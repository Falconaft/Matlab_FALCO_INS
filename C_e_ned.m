function C = C_e_ned(lat, lon)
%C_E_NED  Матрица перехода из локальной NED в ECEF.
%
%   Столбцы матрицы — орты локального трёхгранника [Север, Восток, Вниз],
%   выраженные в осях ECEF. Конвенция та же, что у C_e_n для ENU:
%
%       v_e = C_e_ned * v_ned          (столбец)
%       v_ned = C_e_ned' * v_e
%
%   Для величин, ХРАНЯЩИХСЯ ПОСТРОЧНО (N x 3, как truth.R или res.dr),
%   преобразование записывается умножением справа:
%
%       ned_rows = ecef_rows * C_e_ned
%
%   Связь с ENU (проверено численно, совпадение до нуля):
%       если enu = [E N U], то ned = [N E -U]
%   поэтому матрицы связаны перестановкой столбцов:
%       C_e_ned = [C_e_n(:,2), C_e_n(:,1), -C_e_n(:,3)]
%
%   Вход:  lat, lon - широта, долгота точки [рад]
%   Выход: C (3x3) - матрица NED -> ECEF
%
%   ПРИМЕЧАНИЕ: проверки ортогональности и det = +1 сознательно НЕ делаются
%   здесь — функция вызывается в циклах. Регрессионные проверки вынесены
%   в тестовый код.

    sL = sin(lat);  cL = cos(lat);
    sO = sin(lon);  cO = cos(lon);

    North = [-sL*cO; -sL*sO;  cL];   % орт "Север" в ECEF
    East  = [-sO;     cO;     0 ];   % орт "Восток" в ECEF
    Down  = [-cL*cO; -cL*sO; -sL];   % орт "Вниз" в ECEF (противоположен Up)

    C = [North, East, Down];
end
