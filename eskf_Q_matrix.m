function [Qd, G, Qc] = eskf_Q_matrix(C_b_e, PHI, dt, prof, corrtime, q_model_factor)
%ESKF_Q_MATRIX  Дискретная ковариация шума процесса Qd для 21-состояния ESKF.
%
%   Строит непрерывную Qc (спектральные плотности шумов IMU), матрицу
%   распределения шума G, и дискретную Qd с трапецеидальным сглаживанием.
%
%   Теория: в предсказании ковариации P_{k+1} = Φ·P_k·Φ' + Qd матрица Qd -
%   это добавка неопределённости за такт из-за шумов датчика, не описанных
%   моделью. Без неё фильтр становится "переуверенным" и расходится.
%
%   Порядок шумов (18 = 6 источников по 3 оси), как в KF-GINS Initialize.m:
%     w = [w_va; w_vg; w_bg; w_ba; w_sg; w_sa]
%         VRW(акс) ARW(гиро) GM-bias-гиро GM-bias-акс GM-scale-гиро GM-scale-акс
%
%   Спектральные плотности (диагональ Qc):
%     Qc[va] = VRW²        - белый шум акселерометра (velocity random walk)
%     Qc[vg] = ARW²        - белый шум гироскопа (angular random walk)
%     Qc[bg] = 2·σ_bg²/T   - возбуждающий шум GM-процесса bias гиро
%     Qc[ba] = 2·σ_ba²/T   - возбуждающий шум GM-процесса bias акс
%     Qc[sg] = 2·σ_sg²/T   - возбуждающий шум GM-процесса scale гиро
%     Qc[sa] = 2·σ_sa²/T   - возбуждающий шум GM-процесса scale акс
%   Коэффициент 2σ²/T даёт стационарную дисперсию σ² (Allan-плато), проверено.
%
%   Вход:
%     C_b_e    - матрица ориентации body->ECEF (3x3)
%     PHI      - дискретная матрица перехода (21x21), для сглаживания Qd
%     dt       - шаг времени [с]
%     prof     - профиль IMU (для VRW, ARW, σ и т.д.)
%     corrtime - время корреляции Гаусса-Маркова [с]
%   Выход:
%     Qd - дискретная ковариация шума процесса (21x21)
%     G  - матрица распределения шума (21x18)
%     Qc - непрерывная матрица спектральных плотностей (18x18)

    
    Qc = zeros(18,18);
    
    if nargin < 6 || isempty(q_model_factor)
    q_model_factor = 0;
    end
    assert(q_model_factor >= 0);
    
    % Физическая составляющая
    q_acc_phys = prof.accel.vrw^2;
    q_gyr_phys = prof.gyro.arw^2;
    
    % Дополнительная модельная неопределённость
    q_acc_model = q_model_factor * q_acc_phys;
    q_gyr_model = q_model_factor * q_gyr_phys;
    
    % =====================================================================
    % Шаг 5.7.1: Непрерывная матрица спектральных плотностей Qc (18x18)
    % =====================================================================
    Qc(1:3,1:3) = (q_acc_phys + q_acc_model) * eye(3);
    Qc(4:6,4:6) = (q_gyr_phys + q_gyr_model) * eye(3);

    % Белый шум датчиков (ARW/VRW уже в СИ: [м/с/√с], [рад/√с])
    Qc(1:3,   1:3)   = prof.accel.vrw^2 * eye(3);          % VRW² (акселерометр)
    Qc(4:6,   4:6)   = prof.gyro.arw^2  * eye(3);          % ARW² (гироскоп)

    % Возбуждающий шум процессов Гаусса-Маркова (2σ²/T) - ТОЛЬКО для bias
    Qc(7:9,   7:9)   = 2*prof.gyro.inrun_bias_sigma^2  /corrtime * eye(3);  % bias гиро
    Qc(10:12, 10:12) = 2*prof.accel.inrun_bias_sigma^2 /corrtime * eye(3);  % bias акс

    % SCALE FACTOR = случайная константа (F=0) -> НЕТ возбуждающего шума.
    % Scale проявляется только на 10с разгона (тепловой дрейф ничтожен), оценивается
    % через начальную ковариацию P0[scale]=σ², не через шум процесса. Согласовано с F.
    Qc(13:15, 13:15) = zeros(3);   % scale гиро - нет шума процесса
    Qc(16:18, 16:18) = zeros(3);   % scale акс - нет шума процесса

    % =====================================================================
    % Шаг 5.7.2: Матрица распределения шума G (21x18)
    % =====================================================================
    % Определяет, какие состояния возбуждаются каким шумом.
    % (по KF-GINS InsPropagate.m, но с C_b_e вместо cbn)
    G = zeros(21,18);
    G(4:6,   1:3)   = C_b_e;      % шум акселерометра -> ошибка скорости (через ориентацию)
    G(7:9,   4:6)   = C_b_e;      % шум гироскопа -> ошибка ориентации
    G(10:12, 7:9)   = eye(3);     % GM-шум -> bias гиро
    G(13:15, 10:12) = eye(3);     % GM-шум -> bias акс
    G(16:18, 13:15) = eye(3);     % GM-шум -> scale гиро
    G(19:21, 16:18) = eye(3);     % GM-шум -> scale акс

    % =====================================================================
    % Шаг 5.7.3: Дискретная Qd с трапецеидальным сглаживанием
    % =====================================================================
    % Базовая дискретизация: Qd = G·Qc·G'·dt
    Qd_base = G * Qc * G' * dt;

    % Трапецеидальное сглаживание (учёт эволюции шума по динамике за такт):
    % Qd = (Φ·Qd_base·Φ' + Qd_base)/2  (паттерн KF-GINS InsPropagate.m)
    Qd = (PHI * Qd_base * PHI' + Qd_base) / 2;

    % Симметризация (страховка от численной несимметрии)
    Qd = (Qd + Qd')/2;
end