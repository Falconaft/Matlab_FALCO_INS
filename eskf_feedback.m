function [kf, nav] = eskf_feedback(kf, nav)
%ESKF_FEEDBACK  Применение оценённой ошибки к номинальному состоянию + reset.
%
%   ЗАВЕРШАЮЩИЙ шаг цикла ESKF (closed-loop correction). После measurement
%   update вектор kf.x содержит ОЦЕНКУ ошибки состояния. Здесь эта оценка
%   "вливается" (injection) в номинальное состояние навигатора, после чего
%   error-state ОБНУЛЯЕТСЯ (reset) - вся информация об ошибке уже перенесена
%   в номинал, и накапливать её повторно нельзя.
%
%   КОНВЕНЦИЯ ЗНАКОВ (проверено численно, замкнутый цикл):
%     Ошибка определена как  dx = ИСТИНА - ОЦЕНКА  (конвенция Sola):
%        r_true = r_hat + dr,   C_true = (I + [dpsi x]) * C_hat
%     Невязка при этом:  z = GNSS - оценка,  матрица H = +I.
%     => Коррекция ПРИБАВЛЯЕТСЯ к номиналу (не вычитается!),
%        кватернион корректируется ЛЕВЫМ умножением на dq(+dpsi).
%
%   ВАЖНО: знаки здесь ЖЁСТКО связаны с знаком невязки в eskf_update и с
%   блоками F (все bias/scale с минусом). Менять что-то одно нельзя -
%   расходится весь фильтр.
%
%   Вход:
%     kf  - структура фильтра: kf.x (21x1 error-state), kf.P (21x21)
%     nav - номинальное состояние навигатора:
%           nav.r  (3x1) позиция ECEF [м]
%           nav.v  (3x1) скорость ECEF [м/с]
%           nav.q  (4x1) кватернион Гамильтона body->ECEF [w x y z]
%           nav.bg (3x1) оценка bias гироскопа [рад/с]
%           nav.ba (3x1) оценка bias акселерометра [м/с²]
%           nav.sg (3x1) оценка scale гироскопа [-]
%           nav.sa (3x1) оценка scale акселерометра [-]
%   Выход:
%     kf  - с обнулённым kf.x (reset)
%     nav - скорректированное номинальное состояние (+ обновлённая nav.C_b_e)

    % Индексы блоков error-state
    ir  = 1:3;    iv  = 4:6;    ip  = 7:9;
    ibg = 10:12;  iba = 13:15;  isg = 16:18;  isa = 19:21;

    % =====================================================================
    % Шаг 5.10.1: Коррекция позиции и скорости (аддитивно, ПРИБАВЛЯЕМ)
    % =====================================================================
    % dr = r_true - r_hat  =>  улучшенная оценка: r_hat_new = r_hat + dr
    nav.r = nav.r + kf.x(ir);
    nav.v = nav.v + kf.x(iv);

    % =====================================================================
    % Шаг 5.10.2: Коррекция ориентации (мультипликативно, ЛЕВОЕ умножение)
    % =====================================================================
    % C_true = (I + [dpsi x]) * C_hat  - глобальная (левая) ошибка Sola.
    % В кватернионах это ЛЕВОЕ умножение: q_new = dq(dpsi) (x) q_hat.
    % rotvec2q переводит вектор малого поворота в кватернион (точная экспонента).
    dpsi   = kf.x(ip);
    dq     = rotvec2q(dpsi);
    nav.q  = qmul(dq, nav.q);

    % Нормировка кватерниона (страховка от накопления численной ошибки)
    nav.q  = nav.q / norm(nav.q);

    % Пересчёт матрицы ориентации из скорректированного кватерниона
    nav.C_b_e = q2C(nav.q);

    % =====================================================================
    % Шаг 5.10.3: Коррекция оценок bias и scale (аддитивно, ПРИБАВЛЯЕМ)
    % =====================================================================
    % db = b_true - b_hat  =>  b_hat_new = b_hat + db
    % (эти оценки затем вычитаются из измерений в механизации:
    %  f_corr = (I - diag(sa))*(f_meas - ba) - см. конвенцию error-of-estimate)
    nav.bg = nav.bg + kf.x(ibg);
    nav.ba = nav.ba + kf.x(iba);
    nav.sg = nav.sg + kf.x(isg);
    nav.sa = nav.sa + kf.x(isa);

    % =====================================================================
    % Шаг 5.10.4: RESET error-state
    % =====================================================================
    % Вся информация об ошибке перенесена в номинальное состояние.
    % Если не обнулить - она применится повторно на следующем шаге (двойной учёт).
    kf.x = zeros(size(kf.x));

    % ПРИМЕЧАНИЕ о reset-якобиане ковариации:
    %   Строго (Sola, разд. про ESKF reset) после инъекции ошибки ориентации
    %   ковариацию следует преобразовать: P <- G*P*G', где G = I всюду, кроме
    %   блока ориентации: G_dpsi = I - 0.5*[dpsi x].
    %   При наших малых dpsi (порядок мрад) поправка ~1e-3 от P и практически
    %   не влияет. Оставлено как опция - раскомментировать при необходимости:
    %
    %   G = eye(21);
    %   G(ip, ip) = eye(3) - 0.5*skew(dpsi);
    %   kf.P = G * kf.P * G';
    %   kf.P = (kf.P + kf.P')/2;
end