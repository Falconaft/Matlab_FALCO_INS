function imu = attitude_program(truth, p, c)
%ATTITUDE_PROGRAM  Программа ориентации и синтез идеальных показаний IMU.
%
%   Строит матрицу ориентации C_b_e на всей траектории и синтезирует то,
%   что измерял бы ИДЕАЛЬНЫЙ IMU: удельную силу в осях тела f^b и
%   абсолютную угловую скорость w_ib^b.
%
%   ПРОГРАММА ОРИЕНТАЦИИ:
%     ось X тела — вектор скорости, повёрнутый на УГОЛ АТАКИ в вертикальной
%       плоскости (тяга действует вдоль оси тела, отсюда угол атаки);
%     ось Z тела — вниз (составляющая местной вертикали, ортогональная X);
%     ось Y тела — вправо (дополняет до правой тройки);
%     затем поворот на угол КРЕНА вокруг оси X (если задан).
%
%   Это согласовано с динамикой gen_truth_v2: там продольная сила действует
%   вдоль скорости с учётом cos(alpha), нормальная — перпендикулярно.
%   Проверка: боковая составляющая f^b(Y) должна быть машинным нулём.
%
%   Вход:  truth - траектория (gen_truth_v2)
%          p     - параметры (traj_params)
%          c     - константы
%   Выход: imu   - .t, .fb (N x 3), .wib_b (N x 3), .Ceb (3 x 3 x N)

    N  = numel(truth.t);
    dt = truth.dt;

    Ceb   = zeros(3,3,N);
    fb    = zeros(N,3);
    wib_b = zeros(N,3);

    % =====================================================================
    % Шаг 7.6: ПОСТРОЕНИЕ ОРИЕНТАЦИИ И ПРОЕКЦИЯ УДЕЛЬНОЙ СИЛЫ
    % =====================================================================
    for k = 1:N
        r_k = truth.R(k,:)';
        v_k = truth.V(k,:)';

        % Угол крена: постоянный ноль или заданные колебания
        if p.roll_amp_deg > 0
            roll_deg = p.roll_amp_deg * sin(2*pi*p.roll_freq_hz*truth.t(k));
        else
            roll_deg = 0.0;
        end

        C_k = body_frame(r_k, v_k, truth.alpha(k), roll_deg, c);
        Ceb(:,:,k) = C_k;

        % Удельная сила в осях тела: проекция из ECEF
        fb(k,:) = (C_k' * truth.f_ecef(k,:)')';
    end

    % =====================================================================
    % Шаг 7.7: СИНТЕЗ ГИРОСКОПА
    % =====================================================================
    % Угловая скорость body относительно ECEF из производной матрицы:
    %   dC_b_e/dt = C_b_e * [w_eb^b x]   =>   [w_eb^b x] = C_b_e' * dC_b_e/dt
    % Производную берём центральной разностью, вектор извлекаем как
    % антисимметричную часть (подавляет численный шум).
    w_eb_b = zeros(N,3);
    for k = 1:N
        km = max(k-1, 1);
        kp = min(k+1, N);
        Cdot = (Ceb(:,:,kp) - Ceb(:,:,km)) / ((kp-km)*dt);
        W = Ceb(:,:,k)' * Cdot;
        % Антисимметричная часть: 0.5*(W - W')
        w_eb_b(k,:) = 0.5*[ W(3,2)-W(2,3), W(1,3)-W(3,1), W(2,1)-W(1,2) ];
    end

    % Гироскоп измеряет АБСОЛЮТНУЮ угловую скорость:
    %   w_ib^b = w_eb^b + C_b_e' * w_ie^e
    for k = 1:N
        wib_b(k,:) = w_eb_b(k,:) + (Ceb(:,:,k)' * c.WIE)';
    end

    % =====================================================================
    % Упаковка
    % =====================================================================
    imu.t     = truth.t;
    imu.fb    = fb;
    imu.wib_b = wib_b;
    imu.Ceb   = Ceb;
    imu.w_eb_b= w_eb_b;
end


function C = body_frame(r, v, alpha_deg, roll_deg, c)
%BODY_FRAME  Матрица ориентации C_b_e (столбцы = оси тела в ECEF).
%
%   X - вперёд (вектор скорости, повёрнутый на угол атаки вверх)
%   Y - вправо
%   Z - вниз

    % --- Местная вертикаль ---
    [lat, lon, ~] = ecef2lla(r, c);
    Cen = C_e_n(lat, lon);
    up  = Cen(:,3);                        % третий столбец = Верх

    % --- Направление скорости ---
    v_hat = v / norm(v);

    % --- Ось тангажа: горизонталь, перпендикулярная вертикальной плоскости ---
    pitch_axis = cross(up, v_hat);
    n_pa = norm(pitch_axis);
    if n_pa < 1e-9
        % Вырожденный случай: скорость вдоль вертикали
        pitch_axis = cross(up, [1;0;0]);
        n_pa = norm(pitch_axis);
        if n_pa < 1e-9
            pitch_axis = cross(up, [0;1;0]);
            n_pa = norm(pitch_axis);
        end
    end
    pitch_axis = pitch_axis / n_pa;

    % --- Поворот вектора скорости на угол атаки (формула Родрига) ---
    a  = deg2rad(alpha_deg);
    K  = skew(pitch_axis);
    Rot = eye(3) + sin(a)*K + (1-cos(a))*(K*K);
    x_b = Rot * v_hat;
    x_b = x_b / norm(x_b);

    % --- Ось Z (вниз): составляющая -up, ортогональная x_b ---
    down  = -up;
    z_tmp = down - (down' * x_b) * x_b;
    n_z   = norm(z_tmp);
    if n_z < 1e-9
        z_tmp = cross(x_b, pitch_axis);
        n_z   = norm(z_tmp);
    end
    z_b = z_tmp / n_z;

    % --- Ось Y (вправо): дополняет до правой тройки ---
    y_b = cross(z_b, x_b);

    % --- Поворот на крен вокруг оси X ---
    if abs(roll_deg) > 1e-12
        phi = deg2rad(roll_deg);
        Kx  = skew(x_b);
        Rr  = eye(3) + sin(phi)*Kx + (1-cos(phi))*(Kx*Kx);
        y_b = Rr * y_b;
        z_b = Rr * z_b;
    end

    C = [x_b, y_b, z_b];
end
