function c = constants()
%CONSTANTS  Физические константы WGS-84 для симуляции Falco NAV.
%   Единый источник истины: все функции берут константы отсюда, чтобы исключить
%   рассогласование параметров между генератором траектории и навигатором.
    c.MU  = 3.986004418e14;      % [м^3/с^2]  гравитационный параметр Земли
    c.A_E = 6378137.0;           % [м]        большая полуось эллипсоида WGS-84
    c.J2  = 1.082626683e-3;      % [-]        вторая зональная гармоника (сжатие)
    c.W_E = 7.292115e-5;         % [рад/с]    угловая скорость вращения Земли
    c.F_E = 1/298.257223563;     % [-]        сжатие эллипсоида
    c.E2  = c.F_E*(2 - c.F_E);   % [-]        квадрат первого эксцентриситета
    c.WIE = [0; 0; c.W_E];       % [рад/с]    вектор w_ie в осях ECEF (по оси Z)
end
