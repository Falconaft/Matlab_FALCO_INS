function [CD, CL] = aero_coeffs(Mach, alpha_rad)
%AERO_COEFFS  Аэродинамические коэффициенты по числу Маха и углу атаки.
%
%   Таблицы CD0(M) и CL_alpha(M) для типового оперённого снаряда.
%   Характерный трансзвуковой пик сопротивления при M~1.25.
%
%   Вход:  Mach      - число Маха
%          alpha_rad - угол атаки [рад]
%   Выход: CD        - коэффициент лобового сопротивления
%          CL        - коэффициент подъёмной силы

    % Табличные точки
    mach_grid = [0.50, 0.75, 1.00, 1.25, 1.50, 2.00, 3.26];
    cd0_table = [0.350, 0.351, 0.504, 0.534, 0.497, 0.433, 0.350];
    cla_table = [8.80,  9.29,  10.90, 9.79,  9.01,  7.44,  5.20];

    % Линейная интерполяция с зажимом на краях
    M = min(max(Mach, mach_grid(1)), mach_grid(end));
    CD0      = interp1(mach_grid, cd0_table, M, 'linear');
    CL_alpha = interp1(mach_grid, cla_table, M, 'linear');

    % Подъёмная сила линейна по углу атаки
    CL = CL_alpha * alpha_rad;

    % Индуктивное сопротивление: проекция подъёмной силы + квадратичный член
    CD_induced = abs(CL*sin(alpha_rad)) + 0.05*CL^2;
    CD = CD0 + CD_induced;
end
