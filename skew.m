function S = skew(w)
%SKEW  Кососимметричная матрица векторного произведения.
%   Возвращает S такую, что S*v = cross(w, v) для любого вектора v.
%   Используется для записи [w x] в уравнениях вращения и Кориолиса.
    S = [   0   -w(3)  w(2);
          w(3)    0   -w(1);
         -w(2)  w(1)    0  ];
end
