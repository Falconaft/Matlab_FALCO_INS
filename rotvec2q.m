function q = rotvec2q(phi)
%ROTVEC2Q  Вектор поворота -> кватернион [w x y z].
%   phi - вектор, направление = ось поворота, длина = угол поворота [рад].
%   При малых углах возвращает единичный кватернион (защита от деления на ноль).
    a = norm(phi);                       % величина угла поворота
    if a < 1e-12
        q = [1; 0; 0; 0];                % поворот отсутствует
    else
        q = [cos(a/2); (phi/a)*sin(a/2)]; % ось*sin(угол/2), скаляр = cos(угол/2)
    end
end
