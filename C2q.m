function q = C2q(C)
%C2Q  Матрица поворота -> кватернион [w x y z] (метод Шеппарда).
%   Численно устойчивый алгоритм: выбираем формулу по наибольшему диагональному
%   элементу, чтобы избежать деления на малое число и потери точности.
    tr = trace(C);                       % след матрицы

    if tr > 0
        % Базовый случай: след положителен - используем скалярную часть
        S = sqrt(tr + 1)*2;
        w = 0.25*S;
        x = (C(3,2) - C(2,3))/S;
        y = (C(1,3) - C(3,1))/S;
        z = (C(2,1) - C(1,2))/S;
    else
        % След не положителен: выбираем доминирующий диагональный элемент
        [~, i] = max([C(1,1), C(2,2), C(3,3)]);
        if i == 1
            S = sqrt(1 + C(1,1) - C(2,2) - C(3,3))*2;
            w = (C(3,2) - C(2,3))/S;  x = 0.25*S;
            y = (C(1,2) + C(2,1))/S;  z = (C(1,3) + C(3,1))/S;
        elseif i == 2
            S = sqrt(1 + C(2,2) - C(1,1) - C(3,3))*2;
            w = (C(1,3) - C(3,1))/S;  x = (C(1,2) + C(2,1))/S;
            y = 0.25*S;               z = (C(2,3) + C(3,2))/S;
        else
            S = sqrt(1 + C(3,3) - C(1,1) - C(2,2))*2;
            w = (C(2,1) - C(1,2))/S;  x = (C(1,3) + C(3,1))/S;
            y = (C(2,3) + C(3,2))/S;  z = 0.25*S;
        end
    end

    q = [w; x; y; z];
    q = q/norm(q);                       % нормировка (страховка от накопления ошибок)
end
